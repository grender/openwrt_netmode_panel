// Числа, которыми панель живёт во времени.
//
// Каждое перенесено из панели без сборки вместе со своим доводом: они не
// подобраны, а выведены из поведения демона и роутера, и «округлить»
// любое из них — значит поменять поведение, не заметив этого.

/** Опрос статуса. SPEC §7: 1 Гц, без WebSocket и SSE (ADR-0017). */
export const POLL_MS = 1000;

/**
 * Потолок жизни ЗАСЕЯННОГО джоба, от локальных часов в момент получения 202.
 *
 * Не выводится из eta_sec намеренно: у переключения аплинка eta_sec равен 20,
 * а джоб законно идёт полсотни секунд — 20 с на ассоциацию плюс 30 на
 * ожидание IPv4. Засев без потолка означал бы панель, запертую до F5, если
 * опрос так и не увидел джоб.
 */
export const JOB_MAX = 75000;

/**
 * Сколько статус может не обновляться, прежде чем панель перестанет верить
 * своему джобу. К засеву не применяется никогда — у того свой потолок.
 */
export const STATUS_TTL = 15000;

/**
 * Окно молчания службы после смены режима.
 *
 * Демон коммитит режим в UCI ДО того, как служба поднялась, поэтому сразу
 * после переключения «движок не отвечает» — норма, а не отказ.
 */
export const START_GRACE = 20000;

/** Как часто повторять побочный список, который не приехал при живой службе. */
export const RETRY_MS = 5000;

/** Сколько висит уведомление. */
export const TOAST_MS = 6000;

/** Пороги окраски задержки узла. Контракт из макета, а не украшение. */
export const LAT_OK = 55;
export const LAT_WARN = 110;

/** Потолок шкалы задержки: 220 мс — полная полоска. */
export const LAT_FULL = 220;

/** Пороги уровня сигнала, dBm. */
export const SIG_OK = -60;
export const SIG_WARN = -75;
