#!/bin/sh
# OpenAPI — единственный источник правды о маршрутах.
#
# Бэкенд и фронтенд идут параллельно от одного контракта, поэтому расхождение
# должно валить гейт обоих треков, а не всплывать при первом клике в панели.
# Сверяются три списка:
#
#   docs/api/openapi.yaml   ←→   маршруты, зарегистрированные в Go
#                           ←→   литералы fetch() в web/app.js
#
# Правка контракта возвращается к контракту, а не латается по краям: маршрут
# без записи в openapi.yaml — это расширение объёма мимо ADR.
#
# Сверка Go↔контракт ДВУСТОРОННЯЯ, и вторая сторона появилась не от любви к
# симметрии. Ловилось только «маршрут в Go, которого нет в openapi». Обратное —
# путь объявлен в контракте, вызывается панелью, но в Go не зарегистрирован —
# не проверялось ничем: панель дёргает путь из контракта, значит проверка
# «панель против контракта» зелёная, а http.ServeMux на незарегистрированный
# путь отвечает 405. Так в панель уехала мёртвая кнопка «замерить задержку»
# (POST /api/nikki/test): нажатие молча ничего не делало при всех тринадцати
# (столько их было тогда; число историческое)
# зелёных гвардах. Дыру закрывает список UNIMPLEMENTED ниже.
set -eu

SPEC=docs/api/openapi.yaml
[ -f "$SPEC" ] || { echo "check-routes: нет $SPEC" >&2; exit 1; }

# Контракт обязан быть РАЗБИРАЕМЫМ YAML, а не только похожим на него.
#
# Проверка добавлена 2026-09-03, когда выяснилось, что openapi.yaml не
# разбирался ни одним парсером неизвестно с каких пор: в описании
# bridge.ap_access стоял голый скаляр с двоеточием и пробелом внутри
# ("Выведено: есть форвардинг"), и на нём падал ВЕСЬ файл, а не строка.
# Сам этот скрипт сверяет маршруты grep-ом по тексту, поэтому он оставался
# зелёным — и «единственный источник правды о маршрутах» всё это время был
# нечитаем для любого инструмента, который взял бы его всерьёз: генератора
# клиента, валидатора, редактора со схемой.
#
# Парсер берётся какой найдётся. Отсутствие обоих — не отказ: гейт обязан
# работать на машине, где стоит только Go, и превращать разбор YAML в
# обязательную зависимость ради проверки синтаксиса значило бы менять одну
# дыру на другую. Но молчать об этом нельзя, поэтому пропуск печатается.
if command -v ruby >/dev/null 2>&1; then
	ruby -ryaml -e 'YAML.safe_load(File.read(ARGV[0]), aliases: true)' "$SPEC" \
		|| { echo "check-routes: $SPEC не разбирается как YAML" >&2; exit 1; }
	echo "-- check-routes: контракт разбирается как YAML (ruby)"
elif python3 -c 'import yaml' >/dev/null 2>&1; then
	python3 -c 'import sys,yaml; yaml.safe_load(open(sys.argv[1],encoding="utf-8"))' "$SPEC" \
		|| { echo "check-routes: $SPEC не разбирается как YAML" >&2; exit 1; }
	echo "-- check-routes: контракт разбирается как YAML (python)"
else
	echo "-- check-routes: YAML-парсера нет, синтаксис контракта НЕ проверен"
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Пути контракта, СОЗНАТЕЛЬНО не реализованные в Go. Список закрытый: всё, что
# описано в openapi.yaml и не зарегистрировано в Go, обязано быть названо
# здесь поимённо, иначе гейт падает. Смысл записи — не «разрешение», а
# признание: путь виден панели и обязан вести себя как заглушка, а не как
# работающая кнопка (интерфейс + 503, тот же приём, что и у status=hypothesis
# в разведке).
#
# Запись обязана ИСЧЕЗНУТЬ, когда маршрут появится в Go. Это проверяется
# отдельно и валит гейт: список без обратной проверки за пару фаз становится
# свалкой реализованных путей, и сверка тихо перестаёт что-либо значить —
# ровно тот отказ, ради которого она и заводилась.
#
# По одной записи на строку, комментарий над записью объясняет ПОЧЕМУ пути
# ещё нет.
#
# Сейчас список ПУСТ, и это правильное для него состояние: единственная
# запись — POST /api/nikki/test — ушла отсюда вместе с реализацией маршрута
# (RQ-06 закрыт замером на живом роутере). Пустой список ничего не ослабляет:
# проверка «контракт → Go» продолжает валить гейт на любом пути без
# обработчика, просто исключений из неё больше нет.
UNIMPLEMENTED='
'

# Пути верхнего уровня в openapi: две ведущих пробела, затем /api/...
sed -n 's/^  \(\/api[A-Za-z0-9_/{}-]*\):.*/\1/p' "$SPEC" | sort -u > "$tmp/spec"

fail=0

# --- Go ---
if [ -d internal/httpapi ]; then
	grep -rhoE '"(GET|POST|PUT|DELETE) /api[A-Za-z0-9_/{}-]*"' \
		--include='*.go' internal/httpapi 2>/dev/null \
		| tr -d '"' | awk '{print $2}' | sort -u > "$tmp/go" || true
	grep -rhoE 'HandleFunc\("\/api[A-Za-z0-9_/{}-]*"' \
		--include='*.go' internal/httpapi 2>/dev/null \
		| sed 's/.*("//; s/"$//' | sort -u >> "$tmp/go" || true
	sort -u -o "$tmp/go" "$tmp/go"

	if [ -s "$tmp/go" ]; then
		extra=$(comm -13 "$tmp/spec" "$tmp/go")
		if [ -n "$extra" ]; then
			echo "check-routes: маршрут в Go, которого нет в openapi.yaml:"
			echo "$extra" | sed 's/^/  /'
			fail=1
		fi

		# Обратная сторона: контракт → Go.
		printf '%s\n' "$UNIMPLEMENTED" \
			| sed 's/#.*//' | tr -d ' \t' \
			| grep -v '^$' | sort -u > "$tmp/todo"

		gap=$(comm -23 "$tmp/spec" "$tmp/go" | comm -23 - "$tmp/todo")
		if [ -n "$gap" ]; then
			echo "check-routes: путь описан в openapi.yaml, но не зарегистрирован в Go:"
			echo "$gap" | sed 's/^/  /'
			echo "  панель дёргает такой путь и получает 405 от http.ServeMux —"
			echo "  кнопка нарисована и мертва, а все остальные гварды при этом зелёные."
			echo "  Либо зарегистрируйте обработчик, либо внесите путь в UNIMPLEMENTED"
			echo "  в этом скрипте — с причиной, почему его ещё нет."
			fail=1
		fi

		# Забытая запись опаснее пропущенной: пока путь числится
		# нереализованным, сверка его не смотрит вовсе, и маршрут навсегда
		# выпадает из-под контроля обеих сторон.
		done=$(comm -12 "$tmp/todo" "$tmp/go")
		if [ -n "$done" ]; then
			echo "check-routes: путь числится в UNIMPLEMENTED, но в Go уже зарегистрирован:"
			echo "$done" | sed 's/^/  /'
			echo "  уберите запись из UNIMPLEMENTED в этом скрипте — иначе список"
			echo "  превратится в свалку реализованных путей и сверять перестанет."
			fail=1
		fi

		ghost=$(comm -23 "$tmp/todo" "$tmp/spec")
		if [ -n "$ghost" ]; then
			echo "check-routes: путь числится в UNIMPLEMENTED, но его нет и в openapi.yaml:"
			echo "$ghost" | sed 's/^/  /'
			echo "  путь убрали из контракта — уберите и отсюда, список стережёт"
			echo "  разрыв между контрактом и Go, а не хранит историю."
			fail=1
		fi
	else
		echo "   (маршрутов Go пока нет)"
	fi
fi

# --- Панель ---
if [ -f web/app.js ]; then
	grep -ohE "['\"\`]/api[A-Za-z0-9_/-]*" web/app.js 2>/dev/null \
		| sed "s/^['\"\`]//" | sort -u > "$tmp/web" || true

	if [ -s "$tmp/web" ]; then
		# Путь панели может быть конкретным экземпляром шаблона {id};
		# сверяем по префиксу до первой фигурной скобки.
		sed 's/{[^}]*}.*//' "$tmp/spec" | sed 's#/$##' | sort -u > "$tmp/specpfx"
		while IFS= read -r u; do
			[ -z "$u" ] && continue
			# Хвостовой слэш срезается: панель строит путь как
			# '/api/wifi/networks/' + id, и это тот же маршрут, что
			# '/api/wifi/networks/{id}' в контракте.
			base=${u%/}
			if ! grep -qxF "$base" "$tmp/spec" && ! grep -qxF "$base" "$tmp/specpfx"; then
				echo "check-routes: панель дёргает путь вне контракта: $u"
				fail=1
			fi
		done < "$tmp/web"
	fi
fi

[ "$fail" -ne 0 ] && exit 1

echo "-- check-routes: маршруты сходятся с openapi.yaml"
