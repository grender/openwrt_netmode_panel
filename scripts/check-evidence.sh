#!/bin/sh
# Главная защита от галлюцинированных интеграций.
#
# Каждый литерал, которым код обращается наружу — путь HTTP API, порт, путь
# в sysfs, имя объекта ubus — обязан быть процитирован в docs/recon/evidence.json
# со ссылкой на сырой вывод роутера или на строку исходников b4.
#
# Проверка механическая, а не оценочная: агент не может «убедить» её, что
# эндпоинт существует. Либо литерал есть в evidence.json, либо сборка падает.
#
# Сканируются ТОЛЬКО клиентские пакеты. internal/httpapi исключён намеренно:
# там живут наши собственные маршруты, они описаны в docs/api/openapi.yaml
# и проверяются другим скриптом (check-routes.sh).
set -eu

EV=docs/recon/evidence.json
DIRS="internal/b4 internal/nikki internal/luci internal/led internal/executor internal/wireless internal/geosite"

[ -f "$EV" ] || { echo "check-evidence: нет $EV" >&2; exit 1; }

scan=""
for d in $DIRS; do
	[ -d "$d" ] && scan="$scan $d"
done

if [ -z "$scan" ]; then
	echo "-- check-evidence: клиентских пакетов ещё нет, пропуск"
	exit 0
fi

# Литералы в двойных кавычках из НЕтестовых файлов.
#
# Исключение тестов делается --exclude, а не фильтром вывода. Прежняя
# редакция писала `grep -v '_test\.go'` ПОСЛЕ `grep -rhoE -h`, то есть
# отбрасывала не файлы, а строки, внутри которых буквально написано
# «_test.go». Имён файлов в выводе нет вовсе — их убрал -h, — поэтому
# фильтр не отбрасывал ничего, и литералы тестов всё это время шли в
# проверку наравне с боевыми. Гейт при этом молчал: пути Clash API он не
# сканировал вовсе (см. case ниже), а по остальным шаблонам тесты
# случайно не попадали.
lits=$(grep -rhoE '"[^"]+"' --include='*.go' --exclude='*_test.go' $scan 2>/dev/null \
	| tr -d '"' \
	| sort -u || true)

missing=""
for l in $lits; do
	case "$l" in
		# Внешние поверхности, которые обязаны быть подтверждены.
		#
		# /ui* — веб-панель mihomo. Под /api/* она не подпадает (это статика
		# дашборда, а не Clash API), и без отдельного шаблона оказалась бы
		# единственным внешним путём в проекте без механической защиты.
		#
		# /cgi-bin/* — точка входа LuCI на uhttpd. Тот же случай: путь чужой
		# службы, снятый разведкой, и подтверждать его обязан гейт, а не
		# память автора правки.
		# Пути Clash API (/proxies, /providers/*, /version, /delay) добавлены
		# 2026-09-03 вместе с ReloadProvider. До этого весь Clash API мимо
		# гейта проходил: под /api/* он не подпадает — mihomo держит свои
		# маршруты в корне, — и единственным защищённым его путём был /ui*,
		# попавший сюда по отдельному поводу. То есть двадцать девять узлов
		# читались по литералу, который никто не обязан был подтверждать.
		# Адреса GitHub добавлены 2026-09-07 вместе с internal/geosite:
		# каталог наборов geosite читается ЖИВЫМ с чужого сервера, и три
		# литерала — хост API, путь дерева ветки meta и префикс адреса
		# самих правил — это ровно та поверхность, которую нельзя
		# вспоминать по памяти. Ошибка в любом из них проявится не у
		# нас, а на роутере: пустым списком в панели или наборами,
		# которые mihomo молча не скачает.
		# /connections и /logs добавлены 2026-09-14 вместе с наблюдателем
		# трафика устройства (ADR-0043). Их литералы лежали в evidence.json
		# с самой разведки RQ-09, а шаблон их не видел: два пути Clash API
		# снова читались бы по памяти автора. Форма строки журнала при этом
		# не охраняется ничем и охраняться не может — она чужая и без
		# контракта; о её смене говорит счётчик unparsed на живом роутере.
		/api/*|/ui*|/cgi-bin/*|/sys/class/leds/*|network.wireless|network.interface.*|iwinfo|/proxies*|/providers/*|/version|/delay*|/connections*|/logs*|*api.github.com*|/repos/*|*raw.githubusercontent.com*)
			if ! grep -qF "$l" "$EV"; then
				missing="$missing $l"
			fi
			;;
		# Порты — ищем как :NNNN или host:NNNN
		*:9090*|*:7000*)
			p=$(printf '%s' "$l" | grep -oE '[0-9]{4,5}' | head -1)
			if [ -n "$p" ] && ! grep -qF "$p" "$EV"; then
				missing="$missing $l"
			fi
			;;
	esac
done

if [ -n "$missing" ]; then
	echo "check-evidence: литералы не подтверждены в $EV:"
	for m in $missing; do echo "  $m"; done
	echo ""
	echo "Каждый внешний путь, порт и объект ubus обязан быть процитирован"
	echo "со ссылкой на docs/recon/raw/ или на строку исходников b4."
	echo "НЕ дописывай литерал в evidence.json без цитаты — первопричина"
	echo "всегда «фаза начата без разведки», чинить надо гейт, а не код."
	exit 1
fi

# status=hypothesis считается НЕподтверждённым — предупреждаем явно.
if grep -q '"status": *"hypothesis"' "$EV"; then
	echo "check-evidence: ВНИМАНИЕ — в evidence.json есть status=hypothesis."
	echo "  Такие поверхности реализовывать нельзя: интерфейс + 503."
fi

echo "-- check-evidence: внешние литералы подтверждены"
