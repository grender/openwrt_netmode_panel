#!/bin/sh
# Панель должна укладываться в жёсткий предел gzip суммарно (limit ниже).
#
# Бюджет не косметический: файлы отдаёт сам роутер, а страница грузится
# в тот момент, когда с сетью уже что-то не так. Рантайм preact+htm занимает
# 5,2 КБ (5338 Б gzip — число из вывода этого же скрипта, поделённое на 1024
# так же, как он делит; «5.3» в прежней редакции считалось на 1000).
# Остальное — на разметку, стили и логику.
#
# Считается gzip, а не сырой размер, потому что демон отдаёт статику
# с Content-Encoding: gzip — это заодно экономит CPU роутера.
set -eu

# Оба порога пересмотрены после фазы 2 — решение владельца (ADR-0029).
#
# Прежние 60/48 КБ ставились, когда панель весила 44,6 и фазы 2 не было.
# Фаза добавила 12,0 КБ gzip, и вот честная разбивка (замер 5e37b23 против
# рабочего дерева, а не оценка):
#
#   i18n.js  +4,3 КБ — продуктовый текст: девять причин провала (восемь на
#                      момент замера плюс stale_draft, ADR-0028), у каждой
#                      заголовок и объяснение, на двух языках;
#   app.js   +5,6 КБ — код переключения и комментарии к нему;
#   app.css  +2,0 КБ — стили и комментарии.
#
# Первая редакция этого абзаца называла продуктовым текстом все 12 КБ. Это
# было неверно втрое и удобно для того, кто просит поднять порог. Разбивка
# стоит здесь именно поэтому: следующий пересмотр обязан начинаться с неё.
#
# Довод за пересмотр, а не за резку: панель отдаёт САМ РОУТЕР по локальной
# сети — ни CDN, ни внешнего канала, и разница между 57 и 80 КБ gzip по LAN
# неощутима. В бинарь она попадает через go:embed, а у бинаря предел 10 МБ:
# сырая панель ~130 КБ — на три порядка ниже. То есть 60 КБ ограничивали не
# физику, а аппетит.
#
# Резать здесь можно было только комментарии, а ими в этом проекте держатся
# инварианты (почему у .slot minmax, почему снимок id берётся до await).
# Обменять работающие объяснения на цифру — плохая сделка.
#
# Что НЕ отменяется вместе с числом: панель остаётся одностраничной, без
# сборки и без npm. Это ограничение про устройство, а не про байты, и от
# пересмотра порога оно не страдает.
limit=81920
# Порог внимания: горит, когда до стены остаётся около четверти. Порог,
# который горит всегда, не означает ничего — его перестают читать, и
# следующее, уже настоящее, разбухание проходит незамеченным.
warn=65536

if [ ! -d web ]; then
	echo "-- check-web-size: web/ ещё нет, пропуск"
	exit 0
fi

total=0
found=0
for f in $(find web -type f \( -name '*.html' -o -name '*.css' -o -name '*.js' \) \
	-not -path 'web/mock/*' -not -name 'mock-server.*' | sort); do
	n=$(gzip -c "$f" | wc -c | tr -d ' ')
	total=$((total + n))
	found=$((found + 1))
	printf '   %-52s %6s Б gzip\n' "$f" "$n"
done

if [ "$found" -eq 0 ]; then
	echo "-- check-web-size: файлов панели ещё нет, пропуск"
	exit 0
fi

# Числа в сообщениях считаются ИЗ переменных, а не пишутся словами рядом.
# Раньше в текстах стояли литералы «60 КБ» и «48 КБ», и первая же правка
# порога разошлась бы с ними молча: скрипт ругался бы одним числом, а печатал
# другое — то есть врал бы ровно в тот момент, когда его читают.
kb=$(awk "BEGIN{printf \"%.1f\", $total/1024}")
limit_kb=$(awk "BEGIN{printf \"%.0f\", $limit/1024}")
warn_kb=$(awk "BEGIN{printf \"%.0f\", $warn/1024}")

if [ "$total" -gt "$limit" ]; then
	echo "check-web-size: итого ${kb} КБ gzip, предел ${limit_kb} КБ — ПРЕВЫШЕН"
	exit 1
fi

if [ "$total" -gt "$warn" ]; then
	echo "-- check-web-size: итого ${kb} КБ gzip (внимание: порог ${warn_kb} КБ)"
else
	echo "-- check-web-size: итого ${kb} КБ gzip"
fi
