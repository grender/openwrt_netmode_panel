#!/bin/sh
# b4 управляется исключительно через свой HTTP API.
#
# /etc/b4/b4.json не читается и не пишется никогда: b4 сам мигрирует конфиг
# между версиями, и любая наша запись рискует затереть поля, которых мы не
# знаем. Проверено по исходникам: переключение сета через API переживает
# рестарт b4 (src/http/handler/config.go:439), так что дублировать выбор
# в файле незачем.
set -eu

# Комментарии вырезаются: гейт стережёт обращения к файлу, а не упоминания
# в прозе. Запрет объяснять решение в комментарии — худший вид гейта: он
# вынуждает удалять именно те строки, ради которых решение переживёт полгода.
#
# Выражение снимает хвостовой `// ...`, но не трогает `http://` — там перед
# слэшами стоит двоеточие. В скриптах, которые ищут URL (check-evidence.sh),
# этот приём применять нельзя.
strip_comments() {
	sed 's|\([^:]\)//.*|\1|; s|^\s*//.*||'
}

hits=$(for f in $(find internal cmd -name '*.go' 2>/dev/null); do
	strip_comments < "$f" | grep -n 'b4\.json' | sed "s|^|$f:|"
done || true)

if [ -n "$hits" ]; then
	echo "check-b4json: код обращается к b4.json:"
	echo "$hits" | sed 's/^/  /'
	echo ""
	echo "Запрещено. b4 — только через HTTP API, см. docs/recon/b4-api.md."
	exit 1
fi

echo "-- check-b4json: b4.json не упоминается"
