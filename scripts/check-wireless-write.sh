#!/bin/sh
# Инвариант записи фазы 2 (ADR-0026, раздел «б»).
#
# Формулировка, которую этот скрипт стережёт:
#
#   Демон изменяет `disabled` только на пути переключения upstream и только
#   литеральными значениями "0" и "1". Он никогда не удаляет `disabled`. Он
#   не применяет конфигурацию тупым глаголом. Вход записи, разрешающий
#   неоднозначность, ровно один и виден по имени.
#
# Заменяет check-disabled-write.sh, который стерёг формулировку фазы 1
# («disabled пишется ровно в одном месте и только "1"»). Той формулировки
# больше нет: переключение upstream — это и есть запись disabled. Оставленный
# старый гейт запрещал бы фазу 2 механически (ADR-0026, «Рассмотренные
# альтернативы», последняя строка про исключение для пути переключения).
#
# ── На чём стоит каждое правило ───────────────────────────────────────────
#
#   R1  UCIDelete "disabled" запрещён ВСЕГДА — ADR-0026, правило 2 инварианта,
#       и ADR-0004: отсутствие опции означает ВКЛЮЧЕНО. Удаление — это
#       включение сети способом, который в диффе не выглядит как включение.
#       Разрешённого случая не существует ни в одной фазе.
#
#       R1 стережёт ЛИТЕРАЛ, инвариант держит РАНТАЙМ. Греп не исполняет код:
#       `opt := "dis" + "abled"` для него обычная строка, и вычисленное имя
#       опции проходит мимо R1 в принципе — это не дефект правила, это
#       граница метода. Вторая половина запрета живёт в
#       internal/executor/executor.go: функция forbidDeleteDisabled и сентинел
#       ErrDeleteDisabled, вызываются из Exec.UCIDelete и (той же функцией)
#       из Fake.UCIDelete в internal/executor/fake.go. Тот же приём, что с
#       allowedUbusObjects ниже: скрипт стережёт написанное, рантайм —
#       сделанное. Красный R1 и зелёный рантайм — разные сообщения, и ни одно
#       не заменяет другое.
#
#   R2  disabled пишется только литералами "0" и "1" — ADR-0026, правило 1.
#       Не FormatBool, не Sprintf, не переменная, вычисленная выше: значение
#       этой опции — решение, а не данные. Вычисленное значение нельзя
#       прочитать в месте записи, и ошибка в вычислении выглядит как обычный
#       код.
#
#       Рантайм-половина — forbidDisabledValue в internal/executor. Она держит
#       ОБЛАСТЬ значений ("0" и "1"), но не литеральность: откуда взялась
#       строка, в рантайме не видно. Литеральность держит только греп.
#
#   R3  Мест записи ровно три и ровно в двух файлах — ADR-0026, «Что берёт
#       греп»: создание секции с "1" (wifiwrite.go), гашение прочих "1" и
#       включение целевой "0" (upstreamhandler.go). Четвёртое место означает
#       путь записи, о котором ADR не знает.
#
#   R4  Литерал "0" встречается ровно один раз — усиление ADR-0026, правило 1.
#       "0" и есть «включить сеть»: второй такой путь означал бы включение
#       мимо targetSwitchable, мимо validateSwitchTarget и мимо применения.
#       Гашение ("1") безопасно по построению, включение — нет, поэтому у двух
#       литералов разная цена и разная норма.
#
#   R5  Тупого применения в Go нет — ADR-0025: `wifi` целиком ИЗМЕРЕННО роняет
#       домашнюю точку. Применение идёт единственной дорогой — узким глаголом
#       через netmode-wifi. Объекта `network` нет в allowedUbusObjects по той
#       же причине: он выдал бы демону универсальный `network restart`
#       отовсюду, в обход всей узости (upstreamhandler.go, шаг 7).
#
#   R6  Имён входа записи ровно три, и булева флага нет — ADR-0026, «Отвергнут
#       булев параметр». openWrite(r, allowAmbiguous bool) читается в точке
#       вызова как openWrite(r, true), и что именно разрешено, из этой строки
#       не следует. Список БЕЛЫЙ (openWriteCommon, openWriteForSaved,
#       openWriteForSwitch): чёрный ловил бы имя openWrite и пропускал
#       openWriteAny с тем же флагом. Сам флаг ищется отдельно — он может
#       приехать и в разрешённое имя.
#
#   R7  openWriteForSwitch УПОМИНАЕТСЯ ровно один раз вне своего объявления —
#       ADR-0026, таблица двух входов. Это единственный вход, пропускающий
#       Ambiguous; второй означал бы второй обработчик, которому
#       неоднозначность разрешена молча, без ADR. Считаются упоминания, а не
#       вызовы со скобкой: в Go метод — значение, и `f := s.openWriteForSwitch`
#       заводит второй вход при счётчике вызовов, равном одному.
#
#   R8  Путь /usr/local/bin/netmode-wifi живёт в ОДНОМ месте — в executor.go.
#       Правило про написание пути, а не про число вызывающих: второе
#       упоминание означает вторую точку запуска скрипта мимо разбора кодов
#       возврата (ADR-0027) — либо просто разъезжающуюся копию строки.
#
#   R9  Вызывающий ApplyUpstream ровно один и он вне internal/executor —
#       ADR-0025 и ADR-0027: контракт скрипта (коды возврата 0/1/3/4/7 и их
#       разбор в upstreamSentinels) держится тем, что применение зовут из
#       одного места. R8 этого не проверяет: путь можно упомянуть один раз, а
#       звать метод хоть отовсюду. Объявления, реализации и фейк из счёта
#       исключены отбором каталога — они не вызовы.
#
#   R10 Литерал "disabled" не связывается с именем — ADR-0026, «Что берёт
#       греп». Одна строка `const optDisabled = "disabled"` уводит из-под R1,
#       R2, R3 и R4 сразу всё, причём счётчики «ровно три места» и «ровно одно
#       включение» остаются верными: гейт продолжает подтверждать инвариант,
#       которого больше нет.
#
# ── Что означает зелёный цвет этого гейта ─────────────────────────────────
#
# НЕ «нарушения нет». Ровно: «нарушение не написано в той же форме, в какой
# написан разрешённый код».
#
# Гейт — греп, а греп сравнивает ЛИТЕРАЛЫ. Всё, что можно вычислить, собрать
# из кусков, спрятать за именем или получить значением, он не видит и видеть
# не может: `"dis" + "abled"`, `opt := known[k]`, метод, переданный
# переменной. Правила R6, R7 и R10 появились ровно после того, как каждая из
# этих форм прошла зелёной на живом коде.
#
# Отсюда два следствия, и оба обязательны для читателя:
#
#   1. Зелёный здесь не доказательство. Он значит, что известные формы обхода
#      закрыты, и ничего сверх того. Погоня за полной непробиваемостью грепа
#      бессмысленна — она недостижима, и правило, притворяющееся полным,
#      опаснее правила с названной границей.
#
#   2. Там, где греп бессилен ПО ПРИРОДЕ, стоит рантайм-половина, и она
#      названа поимённо в описании правила. На сегодня это R1
#      (forbidDeleteDisabled в internal/executor/executor.go, зовётся из
#      Exec.UCIDelete и Fake.UCIDelete), R2 (forbidDisabledValue там же,
#      зовётся из Exec.UCISet и Fake.UCISet) и R5 (allowedUbusObjects).
#      Правило без рантайм-половины держит только написание.
#
# ── Чего этот гейт принципиально НЕ проверяет ─────────────────────────────
#
# Граница ровно одна (ADR-0026, «Что берёт греп, что держат тесты»): грепу
# доступно только то, что целиком видно в ОДНОЙ строке исходника и не зависит
# от данных. Всё нижеперечисленное — свойства пути выполнения или содержимого
# конфигурации в момент запроса, и держатся они Go-тестами. Читателю этого
# гейта важно знать, что зелёный цвет здесь про них не говорит НИЧЕГО:
#
#   * порядок записи «сначала погасить прочие, потом включить целевую» и один
#     UCICommit на всю партию — из строк не видно ни порядка, ни числа
#     коммитов (TestSwitchOrder*, upstreamhandler_test.go);
#   * отсутствие коммита на пути отказа и адресный revert только своих секций;
#   * `already_selected` только при Single, но не при Ambiguous — зависит от
#     состояния конфигурации, которого в исходнике нет;
#   * что Ambiguous пропускается для переключения и запрещён для правки и
#     удаления — греп видит два имени входов, но не то, кто из них что делает;
#   * гашение ровно станционных секций и неприкосновенность radio1 /
#     wifi-device — свойство данных (ADR-0026, альтернатива «выразить грепом»:
#     получился бы гейт, который не может покраснеть по делу);
#   * таксономия исходов из восьми причин и то, что вердикт выносится по
#     ассоциации, а не по коду возврата;
#   * запись last_fail при неудаче и её очистка при успехе;
#   * неутечка значения key в тексты ошибок (ADR-0012).
#
# Обратное так же верно и потому названо здесь: тест не заметит нового места
# записи disabled в новом пакете, которое никто не вызвал. Ни один из двух не
# покрывает область другого.
set -eu

# Только неtest-код: в тестах запрещённые формы — материал сценария, а не
# нарушение. Проверка кода, который поедет на роутер, и проверка кода, который
# его гоняет, — разные вопросы.
GOFILES=$(find internal cmd -name '*.go' ! -name '*_test.go' 2>/dev/null | sort || true)

if [ -z "$GOFILES" ]; then
	echo "check-wireless-write: не найдено ни одного неtest-файла в internal/ и cmd/." >&2
	echo "  Гейт, которому нечего смотреть, зелёный по недоразумению — это отказ." >&2
	exit 1
fi

fail=0

# Комментарии вырезаются по той же причине, что в check-no-rollback.sh:
# объяснение «почему так, а не иначе» обязано жить рядом с кодом, а не
# изгоняться гейтом. В комментариях выше по дереву намеренно упомянуты и
# openWrite(r, allowAmbiguous), и `network restart`, и путь к netmode-wifi —
# греп-гейт не обязан отличать комментарий от кода, значит обязан его не
# видеть.
strip_comments() {
	sed 's|\([^:]\)//.*|\1|; s|^[[:space:]]*//.*||'
}

# logical склеивает продолжение вызова в ОДНУ строку, сохраняя номер первой.
#
# Без этого гейт врал в обе стороны на одном и том же переносе, который
# gofmt считает нормальным:
#
#	s.ex.UCISet(ctx, "wireless", sec, "disabled",
#		"1")
#
# Правило R2 видело `"disabled",` без значения и печатало «записывается не
# литералом» с рассказом про FormatBool и Sprintf, которых в коде нет; R4
# краснел следом. А перенос строкой выше уводил всю запись из выборки —
# и это уже ложное ЗЕЛЁНОЕ. Признак продолжения — запятая или открывающая
# скобка на конце строки: ровно то, чем gofmt заканчивает перенесённый вызов.
logical() {
	awk '
		function flush() { if (n) { printf "%d:%s\n", n, buf; buf = ""; n = 0 } }
		{
			t = $0
			sub(/[[:space:]]+$/, "", t)
			if (n == 0) { n = NR; buf = t }
			else { sub(/^[[:space:]]+/, "", t); buf = buf " " t }
			if (t ~ /[,(]$/) next
			flush()
		}
		END { flush() }
	'
}

# scan печатает `файл:строка:текст` по всем неtest-файлам без комментариев.
scan() {
	for f in $GOFILES; do
		strip_comments <"$f" | logical | grep -E "$1" | sed "s|^|$f:|"
	done
}

# say — заголовок нарушения с номером правила, затем места, затем что делать.
say() {
	echo "check-wireless-write: $1"
	shift
	printf '%s\n' "$1" | sed 's/^/  /'
	shift
	echo "  $*"
	fail=1
}

count() { printf '%s\n' "$1" | grep -c . || true; }

# ── R1. UCIDelete "disabled" — запрещено всегда ──
hits=$(scan 'UCIDelete' | grep -F '"disabled"' || true)
if [ -n "$hits" ]; then
	say "R1 нарушено — удаление опции disabled запрещено ВСЕГДА:" "$hits" \
		"Секция без disabled считается ВКЛЮЧЁННОЙ (ADR-0004). Включать сеть надо
  записью литерала \"0\" на пути переключения — тогда включение видно в диффе
  как включение (ADR-0026, правило 2)."
fi

# ── R10. Имя опции `disabled` не прячется за именем ──
#
# Одна строка снимала сразу четыре правила:
#
#	const optDisabled = "disabled"
#
# После неё ни `UCIDelete(..., optDisabled)`, ни `UCISet(..., optDisabled, "1")`
# грепу не видны вовсе. Хуже того, счётчики R3 и R4 остаются ВЕРНЫМИ — «ровно
# три места записи», «ровно одно включение», — и гейт уверенно подтверждает
# инвариант, которого больше нет. Ложное зелёное дороже ложного красного
# именно этим: оно выглядит как доказательство.
#
# Поэтому связывание литерала с именем запрещено само по себе. Чтения
# (`s.Options["disabled"]`, ключ карты, тег json) правилом не задеваются: там
# литерал не присваивается имени.
hits=$(scan '[A-Za-z_][A-Za-z0-9_]*[[:space:]]*:?=[[:space:]]*"disabled"' || true)
if [ -n "$hits" ]; then
	say "R10 нарушено — имя опции disabled связано с именем:" "$hits" \
		"После такой строки правила R1–R4 перестают видеть и запись, и удаление,
  но продолжают считать оставшиеся места и показывать зелёный (ADR-0026,
  «Что берёт греп»). Имя опции пишется литералом в самой строке вызова."
fi

# ── Все места записи disabled. Дальше три правила смотрят на этот же список ──
#
# Значение обязано стоять ВПЛОТНУЮ за именем опции: `"disabled", "1"`. Форма
# «где-то в строке есть \"1\"» пропустила бы UCISet(..., "disabled", v) в
# строке, где единица встретилась по другому поводу.
writes=$(scan 'UCISet\(' | grep -F '"disabled"' || true)

if [ -z "$writes" ]; then
	# Ни одного места записи — это не успех. Фаза 2 без записи disabled
	# означает, что переключение перестало работать, а гейт этого не заметил.
	echo "check-wireless-write: R3 нарушено — записи disabled нет НИ ОДНОЙ." >&2
	echo "  Переключение upstream — это и есть запись disabled (ADR-0026)." >&2
	echo "  Либо путь записи исчез, либо он больше не зовётся UCISet, и тогда" >&2
	echo "  этот гейт стережёт пустоту." >&2
	fail=1
else
	# ── R2. Только литералы "0" и "1" ──
	bad=$(printf '%s\n' "$writes" | grep -vE '"disabled",[[:space:]]*"[01]"' || true)
	if [ -n "$bad" ]; then
		say "R2 нарушено — disabled записывается не литералом \"0\" или \"1\":" "$bad" \
			"Значение этой опции — решение, а не данные: вычисленное значение нельзя
  прочитать в месте записи, и ошибка в вычислении выглядит как обычный код
  (ADR-0026, правило 1). Ни FormatBool, ни Sprintf, ни переменная."
	fi

	# ── R3. Ровно три места и ровно два файла ──
	strays=$(printf '%s\n' "$writes" |
		grep -v '^internal/httpapi/wifiwrite\.go:' |
		grep -v '^internal/httpapi/upstreamhandler\.go:' || true)
	if [ -n "$strays" ]; then
		say "R3 нарушено — disabled пишется вне двух разрешённых файлов:" "$strays" \
			"Разрешены только internal/httpapi/wifiwrite.go (создание секции, \"1\") и
  internal/httpapi/upstreamhandler.go (гашение прочих \"1\", включение цели \"0\").
  Новое место записи — это путь, о котором ADR-0026 не знает: сначала ADR,
  потом код."
	fi

	n=$(count "$writes")
	if [ "$n" -ne 3 ]; then
		say "R3 нарушено — мест записи disabled $n, должно быть ровно три:" "$writes" \
			"Три и только три: создание секции (\"1\"), гашение прочих станционных
  (\"1\"), включение целевой (\"0\") — ADR-0026, «Что берёт греп»."
	fi

	# ── R4. Включение — ровно одно, и только в upstreamhandler.go ──
	#
	# Асимметрия с "1" намеренная: погасить лишнюю секцию безвредно, включить
	# — нет. Второй путь включения обошёл бы targetSwitchable (already_selected),
	# validateSwitchTarget (сеть без ssid/пароля/wwan) и применение целиком.
	enable=$(printf '%s\n' "$writes" | grep -E '"disabled",[[:space:]]*"0"' || true)
	ne=$(count "$enable")
	if [ "$ne" -ne 1 ]; then
		say "R4 нарушено — включений сети (запись disabled=\"0\") $ne, должно быть одно:" \
			"${enable:-(ни одного)}" \
			"Литерал \"0\" — это «включить сеть», и такой путь в демоне ровно один:
  шаг включения целевой секции в writeSwitch (upstreamhandler.go). Второй
  означал бы включение мимо проверок цели и мимо применения (ADR-0026)."
	elif ! printf '%s\n' "$enable" | grep -q '^internal/httpapi/upstreamhandler\.go:'; then
		say "R4 нарушено — включение сети живёт не в upstreamhandler.go:" "$enable" \
			"Включать сеть имеет право только путь переключения upstream (ADR-0026,
  раздел «а»): человек назвал секцию по имени, и результат задан нажатием."
	fi
fi

# ── R5. Тупого применения в Go нет ──
#
# Скрипт netmode-wifi зовёт `network reload` сам, внутри своего замка и своего
# разбора кодов (ADR-0027). Те же глаголы, произнесённые из Go, — это вторая
# дорога к применению, которой контракт скрипта не касается.
# Формы `"wifi"` и `"/sbin/"` в списке не для красоты: аргументом команды
# глагол пишется по кускам и мимо шаблона со пробелом —
# `exec.Command("wifi", "reload")` не совпадает с `wifi[[:space:]]+reload`, а
# `"/sbin/" + "wifi"` не совпадает с `/sbin/wifi`. Обе формы воспроизведены.
hits=$(scan '/sbin/wifi|wifi[[:space:]]+reload|network[[:space:]]+restart|"wifi"|"/sbin/"' || true)
if [ -n "$hits" ]; then
	say "R5 нарушено — в Go найдено тупое применение конфигурации:" "$hits" \
		"\`wifi\` целиком ИЗМЕРЕННО роняет домашнюю точку (ADR-0025, отрицательный
  контроль). Применение идёт единственной дорогой — узким глаголом
  ApplyUpstream через /usr/local/bin/netmode-wifi."
fi

# Запуск внешней команды вне internal/executor — тот же запрет, но не по
# написанию глагола, а по способу. Литерал можно собрать из кусков как угодно
# (`"wi" + "fi"`), и перечислять формы бессмысленно; сам вызов exec.Command
# спрятать нельзя. Единственная дверь демона к системе — интерфейс Executor
# (ADR-0015), и это её механическая опора.
hits=$(scan 'exec\.Command' | grep -v '^internal/executor/' || true)
if [ -n "$hits" ]; then
	say "R5 нарушено — внешняя команда запускается вне internal/executor:" "$hits" \
		"Если действия нет в интерфейсе Executor, демон его не совершает (ADR-0015).
  Прямой exec.Command обходит и узость глагола (ADR-0025), и разбор кодов
  возврата (ADR-0027), и проверку имени радио."
fi

# Объект `network` в allowedUbusObjects — тот же тупой глагол, только через
# ubus. Блок ищется по объявлению, а не в известном файле: переезд карты в
# другой пакет не должен превращать правило в вечнозелёное.
mapfiles=$(grep -l 'allowedUbusObjects = map\[string\]bool{' $GOFILES 2>/dev/null || true)
if [ -z "$mapfiles" ]; then
	echo "check-wireless-write: R5 нарушено — объявление allowedUbusObjects не найдено." >&2
	echo "  Закрытый список объектов ubus — рантайм-половина запрета (executor.go)." >&2
	echo "  Пока его нет, правило про объект \`network\` стережёт пустоту." >&2
	fail=1
else
	for f in $mapfiles; do
		block=$(strip_comments <"$f" |
			awk '/allowedUbusObjects = map\[string\]bool{/{on=1} on{print} on&&/^}/{exit}')
		# Якоря на начало строки здесь НЕТ намеренно: вторая пара на той же
		# строке (`"iwinfo": true, "network": true,`) переживает gofmt и
		# потому является устойчивым состоянием, а не опиской. Форма
		# `"network.wireless"` под шаблон не подходит — закрывающая кавычка
		# требуется сразу после слова.
		if printf '%s\n' "$block" | grep -qE '"network"[[:space:]]*:'; then
			say "R5 нарушено — в allowedUbusObjects появился объект \"network\" ($f):" \
				"$(printf '%s\n' "$block" | grep -nE '\"network\"[[:space:]]*:')" \
				"Он выдал бы демону универсальный \`network restart\` отовсюду, в обход
  всей узости применения (ADR-0025; upstreamhandler.go, шаг 7). Разрешены
  только network.wireless, iwinfo и network.interface.wwan."
		fi
	done
fi

# ── R6. Булев параметр не вернулся ──
#
# Правило переписано с чёрного списка на БЕЛЫЙ. Прежняя редакция искала
# буквально `openWrite(` — и `openWriteAny(r, allowAmbiguous bool)` проходил
# мимо: тот же отвергнутый флаг, только под другим именем. Имён входа три, они
# перечислены в ADR-0026, и четвёртое обязано требовать ADR, а не находчивости.
#
# Разрешённые имена вычёркиваются из строки, а не исключаются грепом целиком:
# иначе строка с двумя вызовами (одним законным, одним новым) считалась бы
# законной.
hits=$(scan 'openWrite' |
	sed -E 's/openWrite(Common|ForSaved|ForSwitch)//g' |
	grep 'openWrite' || true)
if [ -n "$hits" ]; then
	say "R6 нарушено — вход записи с именем вне трёх разрешённых:" "$hits" \
		"Единый вход с флагом отвергнут ADR-0026: в точке вызова видно
  openWrite(r, true), а не смысл, и вопрос «кто разрешает запись при
  неоднозначности» перестаёт быть греповским. Переименование флага входа не
  меняет. Разрешены ровно три имени: openWriteCommon (общая часть),
  openWriteForSaved, openWriteForSwitch."
fi

# Сам флаг — отдельно от имени функции: параметр может приехать и в
# разрешённое имя, и тогда белый список выше промолчит.
hits=$(scan 'allowAmbiguous|allowambiguous' || true)
if [ -n "$hits" ]; then
	say "R6 нарушено — вернулся флаг разрешения неоднозначности:" "$hits" \
		"Именно этот параметр отвергнут ADR-0026: в точке вызова видно \`true\`,
  а не смысл. Неоднозначность разрешает ИМЯ входа, а не аргумент."
fi

# ── R7. Единственный вызывающий openWriteForSwitch ──
#
# Строка объявления исключена: определение — не разрешение неоднозначности,
# разрешением является ВЫЗОВ. Ноль вызовов тоже красный: значит вход исчез, и
# кто-то получает гард другой дорогой.
#
# Исключение якорится на НАЧАЛО строки исходника (`^путь:номер:func `), а не
# ищет `func ` где угодно: объявления в Go стоят в нулевой колонке, а `func`
# в середине строки — это замыкание, и вызов внутри однострочного замыкания
# обязан считаться вызовом. `[0-9]+`, а не `[0-9]*`: без хотя бы одной цифры
# шаблон совпадал бы с `:1:func ` внутри строкового литерала.
#
# Считаются УПОМИНАНИЯ имени, а не вызовы со скобкой. В Go метод — значение:
#
#	f := s.openWriteForSwitch
#	g, errResp := f(r)
#
# даёт второй вход, пропускающий Ambiguous, при счётчике `openWriteForSwitch(`,
# равном единице. Воспроизведено. Упоминание без вызова тоже нарушение: имя,
# переданное куда-то значением, разрешает неоднозначность в месте, которого в
# этом файле не видно.
calls=$(scan 'openWriteForSwitch' | grep -vE '^[^:]+:[0-9]+:func ' || true)
nc=$(count "$calls")
if [ "$nc" -ne 1 ]; then
	say "R7 нарушено — упоминаний openWriteForSwitch вне объявления $nc, должно быть одно:" \
		"${calls:-(ни одного)}" \
		"Это единственный вход записи, пропускающий Ambiguous (ADR-0026, таблица
  двух входов). Второй вызывающий — это второй обработчик, которому
  неоднозначность разрешена молча, без ADR."
elif ! printf '%s\n' "$calls" | grep -q '^internal/httpapi/upstreamhandler\.go:'; then
	say "R7 нарушено — openWriteForSwitch зовут не из upstreamhandler.go:" "$calls" \
		"Пропуск Ambiguous оправдан ровно для POST /api/upstream: там неоднозначность
  снимается как определение операции, а не как побочный эффект (ADR-0026)."
fi

# ── R8. Путь к netmode-wifi написан в одном месте ──
#
# Формулировка узкая намеренно: это правило про СТРОКУ, а не про число
# вызывающих. Единственность вызывающего — предмет R9, и раньше R8 обещал её
# шапкой, не проверяя: путь можно упомянуть один раз, а звать ApplyUpstream
# хоть из десяти мест.
hits=$(scan '/usr/local/bin/netmode-wifi' || true)
nh=$(count "$hits")
if [ "$nh" -ne 1 ]; then
	say "R8 нарушено — путь /usr/local/bin/netmode-wifi написан в $nh местах, нужно одно:" \
		"${hits:-(ни одного)}" \
		"Вторая копия строки — это вторая точка запуска скрипта мимо разбора кодов
  возврата (ADR-0027), либо копия, которая разъедется с первой при переезде
  файла. Ноль означает, что применение перестало звать скрипт вовсе."
elif ! printf '%s\n' "$hits" | grep -q '^internal/executor/executor\.go:'; then
	say "R8 нарушено — путь к netmode-wifi написан не в executor.go:" "$hits" \
		"Запуск внешних команд живёт в одном пакете (internal/executor): там же
  проверка имени радио и разбор кодов возврата (ADR-0027)."
fi

# ── R9. Единственный вызывающий ApplyUpstream ──
#
# Считаются вызовы ВНЕ internal/executor: внутри пакета живут объявление
# метода интерфейса, реализация на Exec и реализация на Fake — ни то, ни
# другое, ни третье не является запуском применения.
callers=$(printf '%s\n' "$(scan 'ApplyUpstream\(')" |
	grep -v '^internal/executor/' | grep -v '^$' || true)
ncu=$(count "$callers")
if [ "$ncu" -ne 1 ]; then
	say "R9 нарушено — вызовов ApplyUpstream вне internal/executor $ncu, должен быть один:" \
		"${callers:-(ни одного)}" \
		"Контракт скрипта — коды возврата 0/1/3/4/7 и их разбор в upstreamSentinels
  (ADR-0027). Второй вызывающий обошёл бы таксономию исходов над этим
  разбором, и «занято» стало бы неотличимо от «не применилось». Ноль означает,
  что переключение больше ничего не применяет."
elif ! printf '%s\n' "$callers" | grep -q '^internal/httpapi/upstreamhandler\.go:'; then
	say "R9 нарушено — ApplyUpstream зовут не из upstreamhandler.go:" "$callers" \
		"Применение — последний шаг переключения upstream, и вердикт по ассоциации
  выносится там же (ADR-0025 §3). Вызов из другого места означает применение
  без вердикта."
fi

if [ "$fail" -ne 0 ]; then
	echo ""
	echo "Инвариант записи фазы 2 — ADR-0026, раздел «б». Он не про удобство:"
	echo "каждое из правил закрывает способ включить станционную сеть так, чтобы"
	echo "в диффе это не выглядело как включение. Если решение меняется —"
	echo "сначала ADR, потом код."
	echo ""
	echo "Этот гейт НЕ проверяет порядок записей, единственность коммита,"
	echo "поведение при Ambiguous и таксономию исходов — их держат Go-тесты"
	echo "(см. шапку скрипта). Зелёный здесь про них не говорит ничего."
	exit 1
fi

echo "-- check-wireless-write: инвариант записи фазы 2 соблюдён (R1–R10)"
