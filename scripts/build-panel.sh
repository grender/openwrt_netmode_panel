#!/bin/sh
# Кладёт панель туда, откуда её забирает go:embed, и записывает манифест
# происхождения.
#
# Копия, а не symlink: go:embed не ходит по ссылкам, и сборка на чужой
# машине молча получила бы пустой каталог.
#
# ЗАЧЕМ МАНИФЕСТ. Пока артефакт был побайтовой копией пяти файлов, вопрос
# «собран ли он из того исходника, что лежит рядом» отвечался через cmp.
# Как только между исходником и артефактом появляется преобразование,
# сравнивать нечего — и утверждение приходится записывать прямо:
# вот входы, вот их хеши, вот что из них получилось.
#
# Скрипт называется build, а не sync, уже сейчас — на этапе, где он всё ещё
# копирует. Так гейт, который придёт ему на смену, встаёт на содержимое,
# про которое известно, что оно верное: новая проверка обкатывается на
# пятифайловой панели, а не одновременно с её заменой.
set -eu

DST=internal/httpapi/panel
LOCK=internal/httpapi/panel.lock.json

# sha256 одним именем на macOS и Linux. Считается по stdin: так одна и та же
# функция берёт и файл с диска, и блоб из git (`git cat-file blob | sha256`),
# а гейту не нужен checkout, чтобы проверить коммит.
if command -v sha256sum >/dev/null 2>&1; then
	sha256() { sha256sum | cut -d' ' -f1; }
elif command -v shasum >/dev/null 2>&1; then
	sha256() { shasum -a 256 | cut -d' ' -f1; }
else
	echo "build-panel: нет ни sha256sum, ни shasum — манифест посчитать нечем" >&2
	exit 1
fi

SRC=web/panel

# ─── версия node ───
#
# Мажор МИНИМАЛЬНЫЙ, а не точный (ADR-0035): точный превратил бы обновление
# ноутбука в красный гейт без продуктовой причины. Две строки шелла вместо
# абзаца в README — правило, которое проверяется, а не то, которое просят
# помнить.
want=$(cat "$SRC/.nvmrc")
have=$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)
if [ "$have" -lt "$want" ]; then
	echo "build-panel: нужен Node $want или новее, найден $have" >&2
	exit 1
fi

# ─── зависимости ───
#
# Ставим ТОЛЬКО через npm ci и никогда через npm install: install умеет
# двигать версии внутри диапазонов, и тогда «собери у себя» и «собери на
# деплое» — две разные сборки, а расхождение между ними обнаруживается на
# роутере (ADR-0035).
#
# Но гонять полную переустановку на КАЖДУЮ сборку незачем: npm ci сносит
# node_modules целиком и лезет в сеть, то есть делает сборку панели
# зависимой от интернета там, где зависимости уже стоят и ровно те.
# Признак «те» — отпечаток лок-файла, положенный рядом ПОСЛЕ успешной
# установки. Отпечаток, а не время файла: mtime врёт после git checkout,
# и обе стороны вранья вредны — лишняя переустановка терпима, пропущенная
# нет.
STAMP="$SRC/node_modules/.netmoded-lock"
want_lock=$(sha256 < "$SRC/package-lock.json")
have_lock=$(cat "$STAMP" 2>/dev/null || echo none)

if [ "$want_lock" != "$have_lock" ]; then
	( cd "$SRC" && npm ci --silent )
	printf '%s\n' "$want_lock" > "$STAMP"
fi

# ─── сборка ───

( cd "$SRC" && npm run build )

[ -f "$SRC/dist/index.html" ] || {
	echo "build-panel: сборка не дала $SRC/dist/index.html" >&2
	exit 1
}

# ─── входы ───
#
# Это ГЛОБ по дереву исходников плюс явный список файлов, которые в дерево
# не входят, но пересборку меняют. Честно назвать это графом модулей нельзя:
# Vite манифеста ВХОДОВ не отдаёт, отдаёт манифест выходов.
#
# Дыра у глоба ровно одна: импорт из-за пределов web/panel/. Такой файл в
# список не попал бы, и свёртка входов стала бы ложью — артефакт зависел бы
# от байтов, которых манифест не называет. Поэтому дыра закрыта проверкой
# ниже, а не оговоркой в комментарии.
INPUTS=$(
	{
		find "$SRC/src" -type f \( -name '*.ts' -o -name '*.tsx' -o -name '*.css' -o -name '*.json' \)
		echo "$SRC/index.html"
		echo "$SRC/vite.config.ts"
		echo "$SRC/tsconfig.json"
		echo "$SRC/package.json"
		echo "$SRC/package-lock.json"
	} | LC_ALL=C sort -u
)

for f in $INPUTS; do
	[ -f "$f" ] || { echo "build-panel: нет входного файла $f" >&2; exit 1; }
done

# Импорт наружу из web/panel/ запрещён: он оставил бы вход вне манифеста.
# Три '../' и больше — это уже выход за web/panel/src/*/*, то есть за корень.
outside=$(grep -rn "from '\.\./\.\./\.\./" "$SRC/src" --include='*.ts' --include='*.tsx' || true)
if [ -n "$outside" ]; then
	echo "build-panel: панель импортирует файл за пределами $SRC:" >&2
	echo "$outside" | sed 's/^/    /' >&2
	echo "  такой вход не попадёт в манифест, и происхождение станет ложью." >&2
	exit 1
fi

# ─── артефакт ───
#
# Каталог сносится целиком перед копированием: `go:embed all:` увозит на
# роутер ВСЁ, что найдёт, включая осиротевшие файлы от прошлой сборки.
rm -rf "$DST"
mkdir -p "$DST"
cp -R "$SRC/dist/." "$DST/"

# ─── манифест ───
#
# ФОРМАТ ЖЁСТКИЙ, и это часть контракта с check-panel-build.sh. Он валидный
# JSON, но читается построчно фиксированным sed — иначе гейту понадобился бы
# разборщик JSON, то есть python или ruby, а `make verify` обязан работать,
# имея только Go и POSIX-шелл. Одна запись на строку, два таба отступа,
# запятая у всех кроме последней.
{
	printf '{\n'
	printf '  "inputs": {\n'

	# Хеши входов — git blob sha1, а не sha256 содержимого. Именно потому,
	# что гейт сверяет их с `git rev-parse HEAD:<путь>`: чужой хеш пришлось
	# бы считать через checkout, а blob-хеш коммита известен без него.
	digest_src=""
	first=1
	for f in $INPUTS; do
		h=$(git hash-object "$f")
		[ "$first" = 1 ] || printf ',\n'
		printf '    "%s": "%s"' "$f" "$h"
		first=0
		digest_src="$digest_src$f $h
"
	done
	printf '\n  },\n'

	# Свёртка по всем входам сразу. Нужна не вместо построчной сверки, а
	# рядом с ней: она отвечает на «тот же ли это НАБОР входов», тогда как
	# построчная — на «те же ли файлы». Сортировка обязательна: порядок
	# INPUTS менять можно, а свёртка от этого меняться не должна.
	printf '  "inputs_digest": "%s",\n' "$(printf '%s' "$digest_src" | LC_ALL=C sort | sha256)"

	printf '  "artifact": {\n'
	first=1
	total=0
	sizes=""
	# find, а не список INPUTS: артефакт обязан описываться тем, что реально
	# лежит в каталоге. Список описывал бы намерение, а go:embed увозит факт.
	for f in $(cd "$DST" && find . -type f | sed 's|^\./||' | LC_ALL=C sort); do
		h=$(sha256 < "$DST/$f")
		[ "$first" = 1 ] || printf ',\n'
		printf '    "%s": "%s"' "$f" "$h"
		first=0
		g=$(gzip -9 -c "$DST/$f" | wc -c | tr -d ' ')
		total=$((total + g))
		sizes="$sizes    \"$f\": $g,
"
	done
	printf '\n  },\n'

	# Размеры записываются и НЕ гейтятся ничем.
	#
	# ADR-0032 снял побайтовый гейт и назвал цену: «панель теперь способна
	# расти незамеченной». Число в коммитимом файле отвечает ровно на эту
	# цену — любая правка панели показывает его в диффе, — не возвращая
	# порога. Храповик («падать, если вырос больше чем на X%») отвергнут:
	# это порог, который движется вместе с ростом, а такое ADR-0032 верно
	# назвал не решением, а ритуалом.
	printf '  "sizes_gzip": {\n'
	printf '%s' "$sizes"
	printf '    "total": %s\n' "$total"
	printf '  }\n'
	printf '}\n'
} > "$LOCK"

n=$(find "$DST" -type f | wc -l | tr -d ' ')
kb=$(awk -v b="$(sed -n 's/.*"total": \([0-9]*\).*/\1/p' "$LOCK")" 'BEGIN{printf "%.1f", b/1024}')
echo "-- панель собрана: $n файлов, $kb КБ gzip, манифест в $LOCK"
