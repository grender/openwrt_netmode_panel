#!/bin/sh
# У панели ровно один рантайм и никакого второго фреймворка.
#
# ADR-0032 снял побайтовый гейт размера, потому что рос ТЕКСТ: объяснения в
# комментариях и переводы, и упираться числом в текст — не решение, а ритуал.
# Со сборкой физика роста меняется. Механизм, которым панель реально
# удваивается, — библиотека, а библиотека не текст. Поэтому охраняется
# ПРИЧИНА, а не симптом, и это не возвращение снятого гейта.
#
# Заодно это первый механический сторож у пункта, который ADR-0032 оставил
# в силе, но ничем не подпирал: «ровно один вендоренный рантайм, никакого
# второго фреймворка». До сих пор он жил комментарием в web/vendor/README.md.
#
# Гейт смотрит ТОЛЬКО dependencies. devDependencies не едут на роутер вовсе,
# и запрещать там что-либо значило бы мешать инструментам сборки без всякой
# выгоды для владельца.
#
# Зависимостей нет: sh плюс awk. `make verify` обязан работать на машине,
# где есть только Go и шелл, поэтому разбирать package.json чем-то вроде
# node или jq здесь нельзя — node нужен цели panel, но не проверке.
set -eu

PKG=web/panel/package.json

# Разрешённые рантайм-зависимости. Список закрытый: добавление сюда — это
# решение, а не правка. Если в нём когда-нибудь окажется второй фреймворк,
# он окажется там ЯВНО, отдельным коммитом, с объяснением.
ALLOWED="preact"

[ -f "$PKG" ] || {
	echo "check-panel-deps: нет $PKG" >&2
	echo "  если панель больше не собирается npm — уберите и эту проверку" >&2
	exit 1
}

# Границы блока считаются по строкам-скобкам с известным отступом, а не по
# первому вхождению слова: имя пакета, совпавшее с именем блока, сдвинуло бы
# разбор молча.
deps=$(awk '
	/^  "dependencies": \{$/ { inside = 1; next }
	inside && /^  \},?$/     { exit }
	inside                   { print }
' "$PKG" | sed -n 's|^    "\([^"]*\)".*|\1|p')

# Антивакуум. Убери кто-нибудь блок dependencies целиком или смени отступ —
# разбор придёт пустым, и гейт позеленел бы, не проверив ничего. Ложное
# зелёное хуже отсутствия гварда: полагаться на него к тому моменту будут.
if [ -z "$deps" ]; then
	echo "check-panel-deps: в $PKG не разобрано ни одной зависимости" >&2
	echo "  блок dependencies пуст или разбор съехал — почините разбор, а не глушите проверку" >&2
	exit 1
fi

bad=""
for d in $deps; do
	ok=""
	for a in $ALLOWED; do
		[ "$d" = "$a" ] && ok=1
	done
	[ -n "$ok" ] || bad="$bad $d"
done

if [ -n "$bad" ]; then
	echo "check-panel-deps: у панели появились посторонние рантайм-зависимости:$bad" >&2
	echo "  Разрешено: $ALLOWED" >&2
	echo "  Инструменты сборки кладут в devDependencies — на роутер они не едут." >&2
	echo "  Второй рантайм — это решение (ADR), а не правка package.json." >&2
	exit 1
fi

# Обратная сторона: разрешённое обязано присутствовать. Пустой ALLOWED и
# пустой deps сошлись бы «успешно», и проверка сравнивала бы пустоту с пустотой.
for a in $ALLOWED; do
	printf '%s\n' "$deps" | grep -qxF "$a" || {
		echo "check-panel-deps: в $PKG нет обязательной зависимости $a" >&2
		echo "  если рантайм сменили — это решение, правьте ALLOWED здесь вместе с ADR" >&2
		exit 1
	}
done

n=$(printf '%s\n' "$deps" | wc -l | tr -d ' ')
echo "-- check-panel-deps: рантайм панели — $n зависимость ($(printf '%s' "$deps" | tr '\n' ' '))"
