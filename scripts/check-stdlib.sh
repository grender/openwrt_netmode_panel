#!/bin/sh
# Только стандартная библиотека.
#
# Падает раньше и точнее, чем check-size.sh: чистый stdlib-бинарь этого объёма
# ложится в 5–7 МБ, поэтому превышение 10 МБ всегда означает затащенную
# зависимость — но узнать об этом на пределе размера гораздо хуже, чем здесь.
#
# Пакеты стандартной библиотеки никогда не содержат точку в первом сегменте
# пути; всё внешнее приходит с домена (github.com/..., golang.org/x/...).
set -eu

bad=$(go list -deps ./... 2>/dev/null | grep -E '^[^/]+\.[^/]+/' || true)

if [ -n "$bad" ]; then
	echo "check-stdlib: обнаружены нестандартные зависимости:"
	echo "$bad" | sed 's/^/  /'
	echo ""
	echo "Зависимости запрещены планом. Если она действительно нужна —"
	echo "это решение уровня ADR, а не импорта."
	exit 1
fi

echo "-- check-stdlib: только stdlib"
