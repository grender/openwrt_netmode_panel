// Package safe — общий перехват паники на границе фоновых горутин.
//
// Паника в горутине, у которой нет своего recover, убивает ВЕСЬ процесс.
// Для этого демона цена такая: владелец разом теряет HTTP API, индикацию и
// управление режимом до перезапуска procd — из-за одной операции, которая
// всего лишь не удалась. Отказ одной операции обязан стоить одной операции.
//
// Честная рамка: известной паники на этих путях сегодня нет. Смена режима
// не доходит ни до одного парсера, индексация в дереве защищена, приведений
// типа без `, ok` нет. Это защита в глубину и страховка будущих правок, а не
// тушение пожара. Обратное тоже верно: наличие Do не разрешает писать код,
// который «всё равно поймают» — перехваченная паника остаётся дефектом,
// и стек в журнале нужен ровно затем, чтобы её починили.
//
// Почему помощник общий, а не три локальных `defer` по площадкам (джоб,
// расписание, отложенный таймер индикации): три копии неизбежно разъедутся.
// Одна напишет стек, вторая — только текст причины, третья вернёт nil, и
// паника исчезнет молча. Здесь формат записи и семантика возврата заданы
// один раз и проверены одним тестом.
//
// Do НИЧЕГО не чинит и не переигрывает: демон не приводит систему в порядок
// по собственной инициативе (ADR-0010), а отката нет как класса (ADR-0006).
// Делаются ровно две вещи — причина со стеком целиком уходит в журнал, а
// вызывающий получает ошибку и решает сам.
//
// recover действует только в той горутине, где случилась паника: Do надо
// звать ВНУТРИ горутины, а не оборачивать им `go ...`.
package safe

import (
	"errors"
	"fmt"
	"runtime/debug"
)

// ErrPanic отличает падение от обычного отказа.
//
// Отдельный сорт ошибки нужен вызывающему: «операция вернула ошибку» и
// «операция рухнула на ровном месте» — разные события. Первое бывает в
// нормальной жизни (роутер занят, сети нет), второе всегда означает дефект
// в демоне, и различать их по тексту строки — значит не различать вовсе.
var ErrPanic = errors.New("внутренний сбой демона")

// Do выполняет fn, превращая панику в ошибку.
//
// what — операция человеческими словами по-русски: она попадает и в журнал,
// и в текст ошибки, который увидит владелец. Обычный (не паникующий) возврат
// fn проходит насквозь без изменений — Do не должен быть местом, где
// теряется или переписывается штатная ошибка.
//
// Пустой logf — тишина, как во всех конструкторах демона. Звать Do с nil
// обязано быть безопасно: перехватчик паники, который сам паникует на
// незаполненном поле, хуже его отсутствия.
func Do(logf func(string, ...any), what string, fn func() error) (err error) {
	if logf == nil {
		logf = func(string, ...any) {}
	}

	defer func() {
		r := recover()
		if r == nil {
			return
		}
		// Стек кладётся целиком и одной записью. Обрезанный не показывает,
		// где именно рвануло, — то есть не даёт починить; а разложенный по
		// строкам перемешается в syslog с чужими записями и перестанет
		// читаться как стек.
		logf("паника: %s: %v\n%s", what, r, debug.Stack())
		err = fmt.Errorf("%w: %s: %v", ErrPanic, what, r)
	}()

	return fn()
}
