// Package luci — адрес веб-интерфейса самого роутера.
//
// Клиента здесь нет и не предполагается: LuCI мы не опрашиваем и ничем в нём
// не управляем. Пакет держит ровно одно внешнее знание — где у uhttpd лежит
// точка входа веб-морды, — и превращает его в ссылку для браузера владельца.
package luci

import (
	"net/url"
	"strings"
)

// PanelPath — точка входа LuCI на uhttpd.
//
// Подтверждено разведкой (raw/72-luci-probe.txt): `uhttpd.main.lua_prefix=
// '/cgi-bin/luci=/usr/lib/lua/luci/sgi/uhttpd.lua'` — этот префикс отдан
// интерпретатору LuCI, и проба по петле отвечает именно им: `403 Forbidden`
// с заголовком `x-luci-login-required: yes`. 403 здесь — подтверждение, а не
// отказ: так LuCI просит войти, и в браузере владельца это форма входа.
//
// На корень `/` не ссылаемся сознательно. Он тоже отвечает 200, но это
// статический /www/index.html (`uhttpd.main.home='/www'`, Content-Length 664),
// и его содержимое разведкой НЕ снималось. Куда он ведёт — догадка, а догадка
// в этом проекте не проходит: за ссылкой должен стоять снятый ответ.
//
// Литерал стоит в отдельном пакете, а не в обработчике, намеренно — тем же
// решением, что и nikki.PanelPath. scripts/check-evidence.sh сканирует
// закрытый список клиентских каталогов и internal/httpapi исключает
// специально (там наши собственные маршруты, их сверяет check-routes).
// Тот же «/cgi-bin/luci», написанный в обработчике, был бы внешним путём без
// механической защиты.
const PanelPath = "/cgi-bin/luci"

// PanelURL — адрес веб-интерфейса роутера, пригодный для браузера владельца.
//
// Схема http, и это решение, а не умолчание: `uhttpd.main.redirect_https='0'`
// (raw/72) — редиректа 80→443 нет, оба слушателя подняты (`listen_http`,
// `listen_https`, netstat: uhttpd на 80 и 443). Сертификат при этом
// самоподписанный (`uhttpd.defaults.commonname='OpenWrt'`), то есть https
// встретил бы владельца предупреждением браузера — за тем же самым LuCI.
//
// Порта в адресе НЕТ: 80 — умолчание схемы http, и писать его значило бы
// завести в проекте новый литерал порта, который гейту пришлось бы стеречь
// ради нуля нового знания.
//
// Хост подставляет вызывающий — из заголовка Host своего запроса. Из
// разведки его взять нельзя по той же причине, что у b4 и nikki: 127.0.0.1
// верен для демона, а в браузере владельца указывает на его же ноутбук.
//
// Скобки для IPv6 ставим руками, и это не перестраховка. net.JoinHostPort
// здесь неприменим — порта нет, — а url.URL.String() голый `fd00::1` НЕ
// скобкует: получилось бы `http://fd00::1/cgi-bin/luci`, что браузер разберёт
// как хост `fd00` с портом, то есть тихо неправильную ссылку вместо явной
// ошибки. Ровно об этом предупреждает комментарий b4.PanelURL. Хост приходит
// из panelHost, который скобки снимает, поэтому ставим их обратно сами;
// уже скобленный хост оставляем как есть, чтобы не удвоить.
func PanelURL(host string) (string, bool) {
	if host == "" {
		return "", false
	}
	h := host
	if strings.Contains(h, ":") && !strings.HasPrefix(h, "[") {
		h = "[" + h + "]"
	}
	u := url.URL{Scheme: "http", Host: h, Path: PanelPath}
	return u.String(), true
}
