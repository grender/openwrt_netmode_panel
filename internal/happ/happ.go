// Package happ разбирает подписку провайдера, ориентированную на клиент Happ.
//
// Провайдер отдаёт МАССИВ ПОЛНЫХ КОНФИГОВ Xray — по одному на запись, каждый
// со своими inbounds, routing и outbounds, — а не Clash YAML и не base64.
// Нам из каждого нужен ровно один outbound; всё остальное в записи описывает
// клиент, которым мы не являемся. Формат снят разведкой (docs/recon/happ.md),
// фикстура — docs/recon/raw/90-happ-subscription.json.
//
// Круг 2 по ADR-0001: чужой формат и один клиент к нему. Куда писать
// результат и когда перечитывать — политика, она в internal/subs.
package happ

// Kind — чем запись подписки является для панели.
//
// В одном массиве провайдер держит три разные сущности, и структурно они
// НЕ различаются: запись «⬇️ Обходы белых списков ⬇️» — побайтовая копия
// узла «Германия (БС-3)», вплоть до балансировщика. Провайдер отделяет
// заголовок от узла только оформлением имени, и разбор вынужден делать то
// же самое. Отсюда правило: вид записи — часть контракта, а не догадка
// панели, и он едет с демона вместе с именем.
type Kind string

const (
	// KindNode — обычный узел. Единственный вид, который можно выбрать.
	KindNode Kind = "node"
	// KindAuto — запись «Авто | Лучший сервер»: у провайдера это
	// балансировщик Xray поверх десятка outbounds, то есть группа, а не
	// узел. У нас ей соответствует снятие ручного закрепления (AUTO).
	KindAuto Kind = "auto"
	// KindSeparator — заголовок раздела в списке провайдера. Подключиться
	// нельзя: за именем стоит копия соседнего узла, а не свой сервер.
	KindSeparator Kind = "separator"
	// KindUnsupported — запись, которую конвертер разобрал, но перевести
	// в узел mihomo не смог. Строка остаётся в списке с причиной: молча
	// исчезнувший узел неотличим от узла, которого у провайдера больше
	// нет, и владелец ищет пропажу не там.
	KindUnsupported Kind = "unsupported"
)

// Entry — одна запись подписки в порядке провайдера.
//
// Порядок здесь значим и является главной причиной, по которой манифест
// вообще существует: mihomo отдаёт узлы объектом (map), и авторский порядок
// провайдера — сначала «Авто», потом узлы по регионам, потом заголовок и
// обходы белых списков — в Clash API не сохраняется никак.
type Entry struct {
	Name string `json:"name"`
	Kind Kind   `json:"kind"`
	// Type — тип узла в терминах mihomo (vless, hysteria2, ss). Пусто у всех
	// видов, кроме KindNode.
	Type string `json:"type,omitempty"`
	// Reason — почему запись непригодна. Заполнен только у
	// KindUnsupported и уходит в панель как есть.
	Reason string `json:"reason,omitempty"`
	// Pool — имена узлов, из которых провайдер собирает свой авторежим.
	//
	// Заполняется ТОЛЬКО у KindAuto и только когда в записи есть
	// балансировщик: у провайдера «Авто» это группа Xray поверх
	// отобранных им серверов, и состав этого отбора — единственное, чем
	// режим авто-пула «как в подписке» может наполняться. Имена, а не
	// теги outbound: тег меняется вместе с адресом сервера, а фильтр
	// mihomo работает по именам.
	//
	// omitempty обязателен: манифест, записанный демоном без этого поля,
	// обязан читаться, а записанный с ним — не ломать демон постарше.
	Pool []string `json:"pool,omitempty"`
	// Proxy — готовый объект узла для файла провайдера.
	//
	// В манифест НЕ пишется (json:"-"): манифест хранит порядок и виды,
	// а не второй экземпляр списка узлов. Две копии одних и тех же
	// серверов разъехались бы при первом же частичном сбое записи.
	Proxy map[string]any `json:"-"`

	// unknown — ключи xhttpSettings.extra, которых конвертер не знает и
	// потому не перенёс. Не экспортируется и в манифест не идёт: это
	// сырьё для Summary, а не свойство записи.
	unknown []string
	// poolIDs — отпечатки outbound-ов балансировщика, ещё не переведённые
	// в имена. Промежуточное состояние между двумя проходами разбора:
	// имена узлов к этому моменту не окончательны — их ещё разведёт
	// dedupeNames. В манифест не пишется по той же причине, что Proxy:
	// он хранит решение, а не сырьё, из которого оно получено.
	poolIDs []string
}

// Summary — сколько чего разобрано.
//
// В журнал обновлений (internal/logs) уходит только Nodes — форма записи
// журнала закрыта. Unsupported и Separators сегодня никто не читает: они
// естественная свёртка того же прохода, что считает узлы, и стоят по
// четыре байта; заводить под них потребителя ради симметрии незачем.
//
// UnknownKeys читает планировщик: одна строка в журнале демона о ключах,
// которые подписка принесла, а мы не перенесли, — это единственный след
// того, что провайдер сменил формат. Без неё узел «то работает, то нет»
// (см. xhttp.go про паддинг), а ни в панели, ни в журнале нет ни одной
// зацепки.
type Summary struct {
	Nodes       int `json:"nodes"`
	Unsupported int `json:"unsupported"`
	Separators  int `json:"separators"`
	// UnknownKeys — отсортированный список без повторов; пусто — ничего
	// неизвестного не встретилось.
	UnknownKeys []string `json:"unknown_keys,omitempty"`
}
