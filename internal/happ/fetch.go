package happ

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"time"
)

const (
	// fetchTimeout — весь запрос целиком, вместе с чтением тела.
	//
	// Шестьдесят секунд, а не пять: подписка — сотня килобайт с чужого
	// сервера через тот самый канал, который сейчас, возможно, и чинится
	// этим обновлением. Обновление подписки происходит раз в сутки по
	// расписанию, и торопиться ему некуда.
	fetchTimeout = 60 * time.Second

	// maxBody — потолок тела ответа. Больше — отказ, а НЕ усечение.
	//
	// Логика ровно та же, что у stdout внешних команд в ADR-0022: тело
	// разбирается, а молча обрезанный JSON даёт загадочную ошибку парсера,
	// и владелец идёт искать поломку в нашем разборе вместо болтливого
	// сервера. Поэтому усечённые байты наверх не отдаются вовсе.
	//
	// Четыре мегабайта — сорокакратный запас против снятых 98 КБ (98 292 Б)
	// на 30 записей. Упереться в него легитимно значит получить от провайдера
	// больше тысячи записей.
	maxBody = 4 << 20

	// userAgent — часть контракта с провайдером, а не вежливость.
	//
	// Ответ ЗАВИСИТ ОТ User-Agent, и зависит не оформлением, а товаром: на
	// "Happ" приходит массив из 30 полных конфигов Xray (~98 КБ), на
	// clash-подобный UA — собранный за нас Clash-профиль на 15 узлов, где
	// нет ни одного xhttp-узла, ни одной записи обхода белых списков, ни
	// разделителя, а порядок свой. Сменить эту строку — значит получить
	// другой товар и молча потерять половину подписки.
	//
	// Именно "Happ": это UA, на котором формат снят разведкой, а не тот,
	// про который мы догадались (docs/recon/happ.md).
	userAgent = "Happ"
)

// ErrNotHTTPS — адрес подписки не по https.
//
// В адресе лежит идентификатор подписки — то есть доступ ко всем серверам
// владельца. Отдать его по http значит показать этот идентификатор каждому
// на пути; отказ здесь дешевле утечки, а «зато работает» на роутере с
// меняющимся аплинком стоит слишком дорого.
var ErrNotHTTPS = errors.New("happ: адрес подписки обязан быть https")

// ErrTooLarge — сервер прислал больше maxBody.
var ErrTooLarge = errors.New("happ: ответ подписки больше допустимого")

// ErrRedirect — подписка ответила перенаправлением, и мы за ним не идём.
//
// Причина не в осторожности вообще, а в двух измеренных фактах. Первый:
// проверка схемы выше смотрит ТОЛЬКО на исходный адрес, а http.Client по
// умолчанию идёт до десяти переходов и схему не перепроверяет — то есть
// ответ «302 Location: http://…» увёл бы всю подписку, вместе с uuid
// абонента и ключами reality, на открытый провод. Второй: при переходе
// между хостами Go САМ ставит заголовок Referer с полным предыдущим
// адресом, включая путь, — то есть вручает идентификатор подписки тому
// хосту, который назовёт перенаправление. Authorization и Cookie stdlib
// при смене хоста снимает, Referer — ставит.
//
// Адрес подписки — фиксированная точка, и снятая разведкой отвечает
// кодом 200 напрямую (docs/recon/happ.md). Поэтому перенаправление здесь
// не «нормальная работа веба», а либо смена адреса, о которой владелец
// должен узнать и вписать её руками, либо чужая рука на пути. Оба случая
// лечатся одинаково: отказ с внятным текстом.
var ErrRedirect = errors.New("happ: подписка отвечает перенаправлением; " +
	"за ним не идём — впишите новый адрес в netmode.main.subscription_url")

// StatusError — сервер подписки ответил кодом, который надо разобрать.
//
// Тип, а не форматированная строка, — чтобы код был доступен через
// errors.As, а не поиском подстроки в тексте: формулировка разъедется при
// первой правке, и тот, кто на неё оперся, узнает об этом последним.
//
// Сегодня по коду никто не ветвится: планировщик при любом отказе пишет
// fail в журнал и ждёт те же двенадцать часов. Смысловая разница между
// 401/403 (протух доступ, чинит владелец) и 5xx (провайдер лёг, пройдёт
// само) есть, и она видна владельцу в тексте, — но в поведение демона
// она не превращена. Тип держит дверь открытой, не обещая того, чего нет.
//
// Адрес в это поле НЕ кладётся: ошибка попадёт в журнал, а в журнале
// идентификатору подписки места нет.
type StatusError struct {
	Code int
}

func (e *StatusError) Error() string {
	return fmt.Sprintf("happ: подписка ответила кодом %d", e.Code)
}

// Fetch скачивает тело подписки.
//
// Адрес не логируется и не подставляется в текст ошибки НИ ПРИ ОДНОМ исходе
// — см. ниже про *url.Error, который приносит его сам.
func Fetch(ctx context.Context, rawurl string) ([]byte, error) {
	u, err := url.Parse(rawurl)
	if err != nil {
		// Ошибка url.Parse — это *url.Error, и он несёт в себе весь
		// разбираемый адрес. Оборачивать её нельзя: секрет уедет в
		// журнал вместе с текстом.
		return nil, errors.New("happ: адрес подписки не разбирается")
	}
	if u.Scheme != "https" {
		return nil, fmt.Errorf("%w (получено: %s)", ErrNotHTTPS, schemeOrNone(u.Scheme))
	}

	return fetch(ctx, newClient(), rawurl)
}

// newClient собирает боевой HTTP-клиент подписки.
//
// Отдельной функцией, а не литералом внутри Fetch, ровно ради одного:
// тест обязан проверять ЭТУ настройку, а не свою копию рядом. Отказ от
// перенаправлений — граница безопасности (см. ErrRedirect), и граница,
// которую проверяют на дубликате, не проверена вовсе.
func newClient() *http.Client {
	return &http.Client{
		Timeout: fetchTimeout,
		// Ни одного перенаправления. Возвращаем свою ошибку, а не
		// http.ErrUseLastResponse: последний ответ на редиректе — это
		// пустое тело с кодом 30x, и разбор упал бы на нём загадочной
		// жалобой парсера вместо честной причины.
		CheckRedirect: func(*http.Request, []*http.Request) error {
			return ErrRedirect
		},
	}
}

// fetch — запрос и чтение тела без проверки схемы.
//
// Отделено от Fetch ради тестов: httptest поднимает сервер на http, и
// проверить потолок тела или разбор кода ответа через публичный Fetch было
// бы нечем — а именно эти два пути и надо доказывать на живом сервере, а не
// на подменённом транспорте.
func fetch(ctx context.Context, client *http.Client, rawurl string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, fetchTimeout)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, rawurl, nil)
	if err != nil {
		return nil, errors.New("happ: запрос к подписке не собирается")
	}
	req.Header.Set("User-Agent", userAgent)

	resp, err := client.Do(req)
	if err != nil {
		return nil, sanitize(err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, &StatusError{Code: resp.StatusCode}
	}

	// Читаем на байт больше потолка: если этот байт пришёл, значит тело в
	// потолок не уложилось. Отличить «ровно maxBody» от «больше» иначе
	// нечем — io.LimitReader об обрыве не сообщает.
	body, err := io.ReadAll(io.LimitReader(resp.Body, maxBody+1))
	if err != nil {
		return nil, sanitize(err)
	}
	if len(body) > maxBody {
		return nil, fmt.Errorf("%w (%d Б)", ErrTooLarge, maxBody)
	}
	return body, nil
}

// sanitize снимает с ошибки адрес запроса.
//
// Главная ловушка этого файла: http.Client.Do возвращает *url.Error, и поле
// URL в нём — ПОЛНЫЙ адрес с идентификатором подписки. Обернуть такую ошибку
// через %w и записать в журнал значит опубликовать секрет владельца, причём
// в самой безобидной на вид строке — «не удалось скачать: Get "https://…"».
// Поэтому наружу отдаётся только вложенная причина (таймаут, отказ TLS,
// недоступный узел), без обёртки url.Error.
func sanitize(err error) error {
	var ue *url.Error
	if errors.As(err, &ue) {
		err = ue.Err
	}
	return fmt.Errorf("happ: подписка не скачалась: %w", err)
}

func schemeOrNone(s string) string {
	if s == "" {
		return "схема не указана"
	}
	return s
}
