package happ

import (
	"bytes"
	"encoding/json"
)

// Render собирает тело файла провайдера для mihomo.
//
// Внутри — JSON, хотя файл на роутере называется .yaml. Это НЕ хак и не
// недоделка: YAML 1.2 объявлен надмножеством JSON, любой YAML-разборщик
// принимает JSON-документ как есть, и ровно так же на этом самом роутере
// поступал прежний скрипт happ2clash (SPEC-backend-router-panel.md:43).
// То есть форма проверена практикой, а не выведена из спецификации.
//
// Не «чините» это генерацией YAML руками: экранирование имён с эмодзи,
// двоеточиями и ведущими пробелами — отдельная задача с отдельными
// граблями, а stdlib YAML не умеет и уметь не будет (зависимостей у проекта
// нет по устройству).
//
// В файл идут ТОЛЬКО узлы: заголовки разделов, «Авто» и неподдержанные
// записи живут в манифесте и в панели, а движку про них знать нечего.
// Порядок подписки сохраняется — mihomo вернёт узлы объектом и порядок
// потеряет, поэтому здесь он последний раз существует в явном виде.
func Render(entries []Entry) []byte {
	proxies := make([]map[string]any, 0, len(entries))
	for _, e := range entries {
		if e.Kind == KindNode && e.Proxy != nil {
			proxies = append(proxies, e.Proxy)
		}
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	// Без экранирования HTML: иначе амперсанд в имени узла превратится в
	// & — формально верно, но владелец читает этот файл глазами при
	// разборе поломок, и подменённое имя ему там мешает.
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(struct {
		Proxies []map[string]any `json:"proxies"`
	}{proxies}); err != nil {
		// Недостижимо: значения в Proxy кладёт только convert.go, и это
		// строки, числа, булевы, срезы строк и вложенные карты — всё
		// сериализуемое. Паника здесь честнее пустого файла: молча
		// записанный `{"proxies":[]}` движок примет, и владелец получит
		// профиль без единого узла вместо внятного отказа.
		panic("happ: узел не сериализуется: " + err.Error())
	}
	return buf.Bytes()
}
