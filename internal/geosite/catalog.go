// Package geosite — живой каталог имён наборов geosite/geoip из
// MetaCubeX/meta-rules-dat (ветка meta).
//
// Зачем каталог вообще нужен. Владелец выбирает наборы доменов по именам
// («youtube», «telegram»), а имена эти живут в чужом репозитории и меняются
// без нашего участия: сегодня их 1899, завтра будет больше. Снимок в бинаре
// протух бы к первой же сборке — панель показывала бы список, которого уже
// нет, а PUT отбивал бы как «неизвестное» имя, которое в репозитории есть.
// Поэтому список читается ЖИВЫМ с GitHub.
//
// Почему только в памяти. Роутер — не сервер: у него флеш на несколько сотен
// перезаписей, и класть на него 60 КБ списка, который каждый раз надо
// перечитывать заново, значит тратить ресурс железа на кэш чужих данных.
// «Ничего на флеш» — решение владельца; перезапуск демона начинает с
// холодного каталога, и это нормально.
//
// Почему кэш всё-таки есть (строго говоря, можно было бы ходить в GitHub при
// каждом обращении панели):
//
//  1. Лимит GitHub — 60 запросов в час на IP без токена, а холодная загрузка
//     стоит четырёх. Пятнадцать обновлений вкладки — и каталог недоступен
//     целый час.
//  2. Время: четыре последовательных запроса с роутера — 1–3 с, а поиск в
//     панели обещан мгновенным.
//  3. Проверка имён при «Применить» не должна зависеть от того, есть ли в
//     эту минуту интернет: опечатка обязана отбиваться сразу, а не через
//     пятнадцать секунд перезапуска туннеля.
//
// Каталог НЕ обновляется по расписанию: если панель не открывают, демон в
// сеть не ходит вовсе.
package geosite

