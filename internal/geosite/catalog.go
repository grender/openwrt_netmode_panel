// Kind — какое из двух деревьев репозитория имеется в виду.
//
// Тип, а не строка: имя вида уезжает и в адрес файла правил, и в имя
// провайдера в конфиге mihomo (nm-geosite-…/nm-geoip-…). Опечатка в строке
// дала бы 404 при скачивании правил уже на роутере, а не при сборке.
type Kind string

const (
	// KindSite — домены (geo/geosite).
	KindSite Kind = "geosite"
	// KindIP — подсети (geo/geoip). Не самостоятельный выбор: ip лишь
	// дополняет набор доменов там, где имя есть в обоих деревьях.
	KindIP Kind = "geoip"
)

// fileURLPrefix — откуда mihomo качает сами правила.
//
// Не api.github.com: raw.githubusercontent.com отдаёт содержимое файла, а не
// метаданные, и не тратит лимит Git API. Ветка в адресе — meta, та же, чьё
// дерево читает каталог: разъехаться адрес правил и список имён не должны.
const fileURLPrefix = "https://raw.githubusercontent.com/MetaCubeX/meta-rules-dat/meta/geo/"

// FileURL — адрес файла правил для mihomo.
//
// Имя НЕ экранируется намеренно: в именах репозитория встречаются '@' и '!'
// (netflix@ads, category-ai-!cn), и оба допустимы в пути URL как есть —
// именно в таком виде их отдаёт GitHub и в таком виде их ждёт mihomo.
// Экранирование превратило бы рабочий адрес в 404.
func FileURL(kind Kind, name string) string {
	return fileURLPrefix + string(kind) + "/" + name + ".mrs"
}

// ValidName — годится ли имя набора для наших файлов.
//
// Набор знаков снят с репозитория (замер 2026-09-07): строчная латиница,
// цифры, '-', '@' и '!' — netflix@ads, category-ai-!cn. Точка,
// подчёркивание и заглавные разрешены на запас: они безобидны везде, куда
// имя уезжает, а появиться в чужом репозитории могут завтра.
//
// Проверка не про аккуратность списка. Имя попадает в две конструкции, где
// посторонний знак ломает не наш разбор, а работу движка:
//
//   - строка правила mixin.yaml в ОДИНАРНЫХ кавычках: апостроф в имени
//     рвёт YAML, и nikki не поднимется при ближайшем перезапуске — том
//     самом, которым владелец применяет наборы;
//   - машинное состояние «sets=имя,имя»: запятая или пробел в имени делают
//     строку неразбираемой, и свой же файл читается как повреждённый.
//
// Экранировать вместо отсева нечего: то же имя уезжает в адрес файла
// правил (FileURL), где экранирование превратило бы рабочий адрес в 404.
// Значит имя либо годится как есть, либо не годится вовсе.
func ValidName(name string) bool {
	if name == "" {
		return false
	}
	// Побайтно, а не по рунам: любой не-ASCII знак обязан отсеяться, и
	// каждый байт многобайтной руны проваливает проверку сам по себе.
	for i := 0; i < len(name); i++ {
		switch c := name[i]; {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9':
		case c == '.', c == '_', c == '-', c == '@', c == '!':
		default:
			return false
		}
	}
	return true
}

// Pack — готовая подборка наборов для панели.
//
// Паки — это не про технику, а про первый экран: владелец, который открыл
// вкладку впервые, не знает ни одного из 1899 имён.
//
// Список ниже фиксирован в коде, и НА ЭТОМ ярусе с каталогом он не
// сверяется: каталога может не быть вовсе (нет интернета, исчерпан лимит
// GitHub), а имя из подборки может исчезнуть из чужого репозитория — и ни
// то ни другое не повод отказаться собрать панель.
//
// Сверка стоит там, где каталог уже в руках. Обработчик
// GET /api/nikki/rulesets/catalog отдаёт подборки, отфильтрованные по
// снимку (httpapi.packsIn): исчезнувшее имя из подборки пропадает, а
// подборка, от которой ничего не осталось, не приходит вовсе — пустая
// рубрика на экране хуже, чем её отсутствие. Последний рубеж прежний: имя,
// пережившее и фильтр, и выбор владельца, отобьёт Validate при сохранении —
// с внятным текстом, а не молча.
type Pack struct {
	ID   string   `json:"id"`
	Sets []string `json:"sets"`
}

