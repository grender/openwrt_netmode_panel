// Catalog — снимок каталога, годный к чтению многими горутинами.
//
// НЕИЗМЕНЯЕМ после того, как попал в Client.cur: обновление кладёт на его
// место новый снимок, а не правит старый. Только поэтому Get может отдать
// указатель наружу без копирования и без замка у читателя — а обработчик
// PUT может спокойно перебирать имена, пока фон качает новую версию.
//
// Дерево GitHub (четыре документа, ~800 КБ) здесь НЕ хранится: оно
// разбирается и выбрасывается, остаётся ~60 КБ результата.
type Catalog struct {
	// Commit — sha корневого дерева ветки meta. Показывается владельцу:
	// это единственный способ понять, насколько список отстал.
	Commit string
	// ETag — валидатор ответа корневого дерева. Ради него всё и затеяно:
	// запрос с If-None-Match, ответивший 304, не тратит лимит GitHub.
	ETag string
	// FetchedAt — когда снимок получен (в том числе продлён через 304).
	FetchedAt time.Time
	// Names — имена geosite, отсортированы: по ним ищет двоичный поиск, и
	// в таком же виде они уезжают в панель.
	Names []string

	// ip — имена, у которых есть ещё и подсети. Карта, а не список: HasIP
	// спрашивают в цикле по всем выбранным наборам.
	ip map[string]bool
}

// newCatalog — единственное место сборки снимка.
//
// Отдельной функцией, чтобы сортировка и карта ip не оказались вторым
// экземпляром в fetch.go: несортированный Names молча сломал бы Has
// (двоичный поиск не жалуется, он просто не находит).
func newCatalog(commit, etag string, at time.Time, names []string, ip map[string]bool) *Catalog {
	sort.Strings(names)
	return &Catalog{Commit: commit, ETag: etag, FetchedAt: at, Names: names, ip: ip}
}

// NewForTest — снимок каталога с заданными именами, БЕЗ похода в сеть.
//
// Существует ради тестов соседних пакетов (internal/mixin проверяет имена
// и проставляет признак подсетей по каталогу). Без неё им пришлось бы либо
// поднимать httptest с четырьмя деревьями GitHub на каждую проверку имени,
// либо собирать Catalog литералом — а карта ip неэкспортируема, и признак
// подсетей всегда оказывался бы ложным, то есть проверка проверяла бы не то.
// В бою не используется: снимки собирает refresh.
func NewForTest(names, ip []string) *Catalog {
	set := make(map[string]bool, len(ip))
	for _, n := range ip {
		set[n] = true
	}
	return newCatalog("test", "", time.Now(), append([]string(nil), names...), set)
}

// Has — есть ли такое имя среди доменных наборов.
//
// nil-приёмник отвечает «нет», а не паникует: спросить могут раньше, чем
// каталог загрузился, и решение «что делать без каталога» принимает
// вызывающий (503 или отказ проверки), а не паника в горутине HTTP.
func (c *Catalog) Has(name string) bool {
	if c == nil {
		return false
	}
	i := sort.SearchStrings(c.Names, name)
	return i < len(c.Names) && c.Names[i] == name
}

// HasIP — есть ли у имени ещё и набор подсетей.
func (c *Catalog) HasIP(name string) bool {
	if c == nil {
		return false
	}
	return c.ip[name]
}

// IPNames — имена с подсетями, отсортированы.
//
// Новый срез на каждый вызов: отдать внутренний было бы приглашением его
// отсортировать или дописать снаружи, а снимок обязан быть неизменяемым.
func (c *Catalog) IPNames() []string {
	if c == nil || len(c.ip) == 0 {
		return nil
	}
	out := make([]string, 0, len(c.ip))
	for n := range c.ip {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

// ErrUnavailable — каталога нет и получить его не удалось.
//
// Один сентинел на все причины отказа при пустом кэше: панели надо ответить
// 503 catalog_unavailable, и ветвиться по тому, был ли это таймаут, 500 или
// обрезанное дерево, ей незачем. Конкретная причина остаётся внутри обёртки
// — и для журнала, и для errors.Is по ErrTruncated/ErrTooLarge.
var ErrUnavailable = errors.New("geosite: каталог недоступен")

// defaultTTL — сколько снимок считается свежим.
//
// Шесть часов, а не минуты: ветка meta пересобирается несколько раз в сутки,
// а спешить нам некуда — имена не протухают за час. Реальная цена частого
// TTL — лимит в 60 запросов и задержка панели, а выигрыш нулевой.
const defaultTTL = 6 * time.Hour

// backgroundTimeout — потолок на ФОНОВОЕ обновление целиком.
//
// Фон не привязан к ctx вызывающего (см. Get): тот уйдёт вместе с ответом
// панели через миллисекунды и убил бы обновление на первом же запросе. Но и
// висеть вечно фону нельзя — четыре запроса по fetchTimeout плюс запас.
const backgroundTimeout = 90 * time.Second

// retryBackoff — пауза после неудачного обновления.
//
// Пять минут, а не «пробовать снова сразу». Просроченный кэш при лежащем
// GitHub означал бы поход в сеть на КАЖДОЕ обращение панели: вкладка
// опрашивается регулярно, каждый опрос стоил бы запроса, и шестьдесят
// запросов в час выбирались бы за минуту — после чего GitHub отвечает 403
// уже всем подряд, включая честную загрузку, когда сеть вернётся. То есть
// без паузы временный отказ провайдера превращается в наведённый на себя
// бан на час. Цена паузы — список имён отстаёт ещё на пять минут; цена
// её отсутствия — каталога нет час.
const retryBackoff = 5 * time.Minute

// Client — каталог с кэшем в памяти.
//
// Нулевое значение рабочее: боевые адрес, HTTP-клиент и TTL подставляются
// сами, журнал молчит. Так же, как у остальных клиентов демона.
type Client struct {
	// BaseURL — корень GitHub API. Пусто → https://api.github.com.
	//
	// Требование «только https» проверяется ТОЛЬКО при пустом BaseURL, то
	// есть для боевого адреса и для всех адресов, которые GitHub присылает
	// в теле ответа. Явно заданный BaseURL — это стенд разработчика или
	// httptest, и там http обязан работать: иначе поведение кэша,
	// потолков и ETag нечем проверить без выхода в сеть.
	BaseURL string
	// HTTP — клиент запросов. nil → собственный: таймаут 15 с и отказ от
	// перенаправлений (см. ErrRedirect).
	HTTP *http.Client
	// TTL — срок свежести снимка. 0 → defaultTTL.
	TTL time.Duration
	// Logf — журнал демона. nil → тишина.
	Logf func(string, ...any)

	mu  sync.Mutex
	cur *Catalog
	// refreshing — идёт ли обновление, фоновое или синхронное.
	//
	// Замок именно на «одно за раз», а не на «по одному на вызывающего»:
	// панель, открытая на трёх устройствах, иначе превратила бы один
	// просроченный кэш в три холодные загрузки, то есть в двенадцать
	// запросов из шестидесяти в час.
	refreshing bool
	// inflight — закрывается, когда идущее обновление закончилось.
	//
	// Нужен ровно холодному пути: там ждущему вызывающему надо ОТДАТЬ
	// результат чужого обхода, а не отказать ему и не пойти в GitHub
	// вторым. Канал, а не sync.Cond: ждать приходится вместе с
	// контекстом вызывающего, а cond в select не участвует.
	inflight chan struct{}
	// retryAfter — раньше этого момента ФОНОВОЕ обновление не начинается
	// (см. retryBackoff).
	//
	// Синхронной попытки холодного пути пауза не касается: без кэша
	// отдавать нечего вовсе, и пять минут гарантированного 503 там, где
	// следующая же попытка могла удаться, — не бережливость, а поломка.
	// То есть вернувшуюся сеть подхватит первое же обращение панели, а
	// пауза сдержит только фон, который никто не ждёт.
	retryAfter time.Time
	// retryHold — длина паузы после неудачи. 0 → retryBackoff. Только
	// тесты: ждать в тесте пять минут нечем.
	retryHold time.Duration
	// def — лениво собранный боевой HTTP-клиент. Один на клиент, а не на
	// запрос: четыре запроса подряд обязаны идти по одному соединению.
	def *http.Client
	// refreshed — хук для тестов: вызывается после каждого ФОНОВОГО
	// обновления, когда флаг refreshing уже снят. В бою nil.
	//
	// Нужен затем, что иначе тест ждал бы чужую горутину сном «на глазок»
	// — то есть был бы то зелёным, то красным в зависимости от нагрузки
	// машины, а такой тест не проверяет ничего.
	refreshed func()
}

// Get — каталог для панели и для проверки имён.
//
// Три исхода, и все три без ожидания сети там, где кэш уже есть:
//   - свежий кэш — он же;
//   - просроченный кэш — он же СРАЗУ, а обновление уходит в фон. Владелец
//     видит список мгновенно; отставание на шесть часов в списке имён никого
//     не трогает, а секунда ожидания — трогает;
//   - кэша нет — синхронная загрузка: отдавать нечего, ждать придётся. Её
//     неудача не тупик: обход доводится фоном, и следующее обращение
//     находит готовый список (см. cold).
func (c *Client) Get(ctx context.Context) (*Catalog, error) {
	if cur := c.Current(); cur != nil {
		if c.Stale(cur) {
			c.startRefresh()
		}
		return cur, nil
	}
	return c.cold(ctx)
}

// cold — каталога нет вовсе: ответить, не сходив в сеть, нечем.
//
// Два правила, и оба про чужой лимит в 60 запросов в час.
//
// Обход один на всех. Пока кто-то идёт по деревьям, остальные ЖДУТ его, а не
// начинают свой: панель, открытая на трёх устройствах, иначе превратила бы
// пустой кэш в три обхода, то есть в двенадцать запросов. Ждут ровно столько,
// сколько отпущено вызывающему: его срок — восемь секунд бюджета побочного
// списка панели, и висеть дольше него бессмысленно.
//
// Неудача синхронной попытки запускает ОДИН фоновый обход со своим сроком.
// Без этого холодная загрузка на медленном аплинке не заканчивается никогда:
// четыре последовательных запроса в GitHub не укладываются в восемь секунд,
// каждая попытка умирает вместе с запросом панели, кэш остаётся пустым — и
// «Повторить» начинает всё сначала до бесконечности. С фоном первое же
// нажатие оплачивает загрузку, а второе находит готовый список.
func (c *Client) cold(ctx context.Context) (*Catalog, error) {
	wait, mine := c.begin()
	if !mine {
		select {
		case <-wait:
		case <-ctx.Done():
			return nil, fmt.Errorf("%w: %w", ErrUnavailable, ctx.Err())
		}
		if cur := c.Current(); cur != nil {
			return cur, nil
		}
		// Чужой обход не удался. Своей причины у нас нет — она уехала в
		// журнал того, кто ходил, — но и молчать нельзя: панели нужен
		// текст под 503.
		return nil, fmt.Errorf("%w: обход GitHub не удался", ErrUnavailable)
	}

	cat, err := c.refreshHeld(ctx)
	if err == nil {
		return cat, nil
	}
	// Фон запускается ПОСЛЕ refreshHeld: тот снял с себя флаг «идёт
	// обновление», и без этого startRefresh увидел бы занято и не сделал
	// бы ничего. Причина отказа не разбирается намеренно — оборванный
	// контекст панели и лежащий GitHub лечатся одинаково: попыткой, за
	// которой никто не стоит с секундомером. От серии попыток при
	// по-настоящему недоступном GitHub бережёт retryAfter.
	c.startRefresh()
	// Двойная обёртка: наружу ошибка опознаётся как ErrUnavailable
	// (панель отвечает 503), а внутрь остаётся видна конкретная
	// причина — ErrTruncated, ErrTooLarge, код ответа.
	return nil, fmt.Errorf("%w: %w", ErrUnavailable, err)
}

// Current — что лежит в кэше сейчас. Может быть nil.
func (c *Client) Current() *Catalog {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.cur
}

// Stale — снимок старше TTL (или его нет вовсе).
//
// Отдельный метод, потому что просроченность видит и панель: старый список
// отдаётся с признаком stale, чтобы владелец понимал, почему только что
// появившегося в репозитории имени в списке нет.
func (c *Client) Stale(cat *Catalog) bool {
	return cat == nil || time.Since(cat.FetchedAt) > c.ttl()
}

func (c *Client) ttl() time.Duration {
	if c.TTL > 0 {
		return c.TTL
	}
	return defaultTTL
}

func (c *Client) logf(format string, args ...any) {
	if c.Logf != nil {
		c.Logf(format, args...)
	}
}

// begin — попытка взять обновление на себя.
//
// mine=true — взяли, и обязаны потом позвать end(); mine=false — обновление
// уже идёт, а wait закроется, когда оно кончится.
func (c *Client) begin() (wait <-chan struct{}, mine bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.refreshing {
		return c.inflight, false
	}
	c.refreshing = true
	c.inflight = make(chan struct{})
	return c.inflight, true
}

// end — обновление закончилось: флаг снят, ждущие разбужены.
func (c *Client) end() {
	c.mu.Lock()
	ch := c.inflight
	c.refreshing = false
	c.inflight = nil
	c.mu.Unlock()
	close(ch)
}

// refreshHeld — обновление с уже взятым флагом; снимает его в любом исходе.
//
// Снятие через defer, а не в конце тела: залипший refreshing означал бы, что
// каталог не обновится больше НИКОГДА до перезапуска демона, а ждущие на
// холодном пути повисли бы до своего срока.
func (c *Client) refreshHeld(ctx context.Context) (*Catalog, error) {
	defer c.end()
	return c.refresh(ctx)
}

// startRefresh запускает фоновое обновление, если оно ещё не идёт.
func (c *Client) startRefresh() {
	c.mu.Lock()
	held := time.Now().Before(c.retryAfter)
	c.mu.Unlock()
	if held {
		return
	}
	if _, mine := c.begin(); !mine {
		return
	}

	go func() {
		defer func() {
			c.end()
			if c.refreshed != nil {
				c.refreshed()
			}
		}()

		// safe.Do ВНУТРИ горутины, а не вокруг `go` (ADR-0021): recover
		// работает только там, где случилась паника, а паника в горутине
		// без своего recover убила бы весь демон — владелец разом
		// потерял бы и API, и управление режимом из-за неудачной
		// загрузки списка имён.
		_ = safe.Do(c.Logf, "фоновое обновление каталога geosite", func() error {
			// Свой контекст, а не контекст вызывающего: тот уйдёт
			// вместе с ответом панели через миллисекунды и убил бы
			// обновление, ради которого всё затевалось.
			ctx, cancel := context.WithTimeout(context.Background(), backgroundTimeout)
			defer cancel()

			if _, err := c.refresh(ctx); err != nil {
				c.holdRetry()
				// Отказ фона — не отказ операции: старый каталог
				// остался и продолжает работать. Наверх ошибка не
				// уходит вовсе, поэтому единственный след — вот эта
				// строка; без неё «список не пополняется» осталось
				// бы необъяснимым.
				c.logf("каталог geosite: не обновлён: %v", err)
			}
			return nil
		})
	}()
}

// holdRetry откладывает следующую попытку обновления.
//
// Длина паузы читается ПОД замком вместе с записью: retryHold живёт в том
// же ряду полей, что refreshing и retryAfter, и читать его врозь значило бы
// завести единственное поле клиента с другим правилом доступа.
func (c *Client) holdRetry() {
	c.mu.Lock()
	defer c.mu.Unlock()
	hold := c.retryHold
	if hold <= 0 {
		hold = retryBackoff
	}
	c.retryAfter = time.Now().Add(hold)
}

// store публикует новый снимок.
//
// Пауза снимается здесь же: обновление удалось, держать следующее незачем,
// а оставленный retryAfter пережил бы восстановление сети и задержал
// обновление после того, как оно уже заработало.
func (c *Client) store(cat *Catalog) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.cur = cat
	c.retryAfter = time.Time{}
}
