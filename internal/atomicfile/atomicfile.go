// Package atomicfile пишет файлы так, чтобы читатель никогда не увидел
// половину записи.
//
// Вынесено из internal/subs (первый писатель — файл провайдера и манифест
// подписки), потому что второй писатель — mixin nikki (/etc/nikki/mixin.yaml,
// ADR геосайтов) — нуждается в ровно той же гарантии, но с другими правами
// на файл. Права — единственное, что менялось: механика O_EXCL/fsync/rename
// одна на всех вызывающих.
package atomicfile

import (
	"fmt"
	"os"
)

// Write пишет data по пути path через временный файл, fsync и rename, с
// правами доступа perm.
//
// Два разных обещания, и оба здесь выполняются, а не подразумеваются.
//
// Атомарность ВИДИМОСТИ даёт rename: по рабочему имени в любой момент лежит
// либо старый файл целиком, либо новый целиком, половины не бывает.
// ДОЛГОВЕЧНОСТЬ даёт Sync перед rename: без него данные могли остаться в
// кэше страниц, а переименование — уже дойти до флеша, и после обрыва
// питания по рабочему имени оказался бы файл нулевой длины. Файлы этого
// пакета живут во флеше роутера, который питается от розетки без ИБП, — это
// не теоретический риск. Каталог не синхронизируется: без этого после
// обрыва возможен откат к СТАРОМУ файлу, а не к пустому, и это приемлемо —
// потерянная запись повторится по своему расписанию у вызывающего.
//
// Временный файл открывается с O_EXCL, а не через os.WriteFile. Тот
// открывает с O_TRUNC, идёт по символической ссылке и оставляет права
// существующего файла: подложенная в чужой каталог ссылка path.tmp увела бы
// содержимое по чужому пути, а .tmp от прерванной записи с чужими правами
// был бы перезаписан и переименован на место как есть. O_EXCL отвергает и
// то и другое; залежавшийся .tmp снимается перед открытием (Remove ссылку
// не разыменовывает — снимается сама ссылка, а не её цель). Права задаются
// при создании, отдельный Chmod не нужен.
//
// Каталог НЕ создаётся намеренно: отсутствие каталога назначения означает,
// что его владелец (nikki, happ2clash и так далее) на этом роутере не
// разворачивался, и молча заводить ему каталог значит чинить не свою
// поломку в обход её владельца. Ошибка с путём внятнее.
func Write(path string, data []byte, perm os.FileMode) (err error) {
	tmp := path + ".tmp"
	// Остаток прерванной записи; отсутствие — норма, ошибку не смотрим.
	os.Remove(tmp)

	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, perm)
	if err != nil {
		return fmt.Errorf("временный файл: %w", err)
	}
	// Любой отказ ниже — мусор во флеше убираем, ровно там, где места
	// могло не хватить.
	defer func() {
		if err != nil {
			os.Remove(tmp)
		}
	}()

	if _, err = f.Write(data); err != nil {
		f.Close()
		return fmt.Errorf("запись временного файла: %w", err)
	}
	if err = f.Sync(); err != nil {
		f.Close()
		return fmt.Errorf("fsync временного файла: %w", err)
	}
	if err = f.Close(); err != nil {
		return fmt.Errorf("закрытие временного файла: %w", err)
	}
	if err = os.Rename(tmp, path); err != nil {
		return fmt.Errorf("замена файла: %w", err)
	}
	return nil
}
