package subs

import (
	"netmoded/internal/happ"
	"netmoded/internal/nikki"
)

// reasonMissingInLive — почему узел из подписки не виден в mihomo.
//
// Текст один на все такие строки и живёт константой, а не собирается в
// цикле: он уезжает в панель как есть, и владелец должен узнавать его
// с первого взгляда, а не сверять формулировки между узлами.
const reasonMissingInLive = "узел есть в подписке, но mihomo его не показывает: " +
	"движок либо не принял этот узел (например, транспорт, которого его версия " +
	"не умеет), либо ещё не перечитал файл провайдера"

// Order склеивает авторский порядок подписки с живым состоянием mihomo.
//
// Порядок приходится хранить отдельно, потому что Clash API его теряет:
// /proxies отдаёт узлы объектом, а список участников группы — это уже
// раскладка движка, а не провайдера. Замысел провайдера — сначала «Авто»,
// потом узлы по регионам, потом заголовок и обходы белых списков — виден
// только в манифесте.
//
// Ни один из двух источников не главнее другого, и в этом весь смысл
// функции: манифест знает ПОРЯДОК и ВИД записи, mihomo знает ЖИВОСТЬ и
// ЗАДЕРЖКУ, и ни один не знает того, что знает другой.
//
// live — ответ nikki.Proxies(). group — имя группы, участников которой
// показываем. manifest — записи подписки в порядке провайдера.
func Order(live map[string]nikki.Proxy, group string, manifest []happ.Entry) []Member {
	if len(manifest) == 0 {
		return fromLiveOnly(live, group)
	}

	// seen нужен не ради экономии: провайдер повторяет одно имя в разных
	// разделах (узел и его копия под заголовком «обходы»), и без проверки
	// панель показала бы два одинаковых пункта, из которых второй ничего
	// нового не выбирает.
	seen := make(map[string]bool, len(manifest))
	out := make([]Member, 0, len(manifest))

	for _, e := range manifest {
		if seen[e.Name] {
			continue
		}
		seen[e.Name] = true

		if e.Kind != happ.KindNode {
			// Разделитель, «Авто» и заведомо непригодная запись: узла в
			// mihomo для них нет и быть не должно, искать его в live —
			// значит принять случайное совпадение имён за свой узел.
			out = append(out, Member{
				Proxy:  nikki.Proxy{Name: e.Name, Type: e.Type},
				Kind:   e.Kind,
				Reason: e.Reason,
			})
			continue
		}

		if p, ok := live[e.Name]; ok {
			// Живой узел целиком: задержка, alive, тип — всё из движка.
			// Имя из манифеста здесь уже не нужно, оно совпало.
			out = append(out, Member{Proxy: p, Kind: happ.KindNode})
			continue
		}

		// Узел записан в файл провайдера, а движок его не показывает.
		// Выбросить строку молча нельзя: исчезнувший узел неотличим от
		// узла, которого у провайдера больше нет, и владелец пойдёт
		// искать пропажу в подписке вместо движка.
		out = append(out, Member{
			Proxy:  nikki.Proxy{Name: e.Name, Type: e.Type},
			Kind:   happ.KindUnsupported,
			Reason: reasonMissingInLive,
		})
	}

	// Живые участники, которых в манифесте нет, — в конец, в порядке
	// mihomo. Манифест может отставать от файла провайдера: его обновили
	// мимо демона, или запись прошла, а манифест сохранить не успели.
	// Прятать реально доступный узел из-за устаревшего манифеста значит
	// сделать список хуже, чем он был бы вовсе без манифеста.
	for _, p := range nikki.Members(live, group) {
		if seen[p.Name] {
			continue
		}
		seen[p.Name] = true
		out = append(out, Member{Proxy: p, Kind: happ.KindNode})
	}

	return out
}

// fromLiveOnly — список без манифеста: ровно то, что панель показывала до
// появления подписки.
//
// Это путь свежей установки, где обновление ещё ни разу не проходило, и он
// обязан работать: иначе демон выглядел бы сломанным ровно до первого
// успешного скачивания подписки — то есть у того, у кого она не качается.
//
// nil против пустого среза сохранён намеренно: nikki.Members отдаёт nil,
// когда группы нет вовсе, и панель отличает «группы нет» от «группа пуста».
func fromLiveOnly(live map[string]nikki.Proxy, group string) []Member {
	ms := nikki.Members(live, group)
	if ms == nil {
		return nil
	}
	out := make([]Member, 0, len(ms))
	for _, p := range ms {
		out = append(out, Member{Proxy: p, Kind: happ.KindNode})
	}
	return out
}
