package httpapi

import (
	"sync"
	"time"
)

// failStore — последняя неудачная смена внешней сети.
//
// Смена upstream — единственная операция панели, которая может оборвать
// канал, через который её запустили. Джоб живёт в памяти и виден в
// /api/status, но браузер, потерявший связь на сорок секунд, теряет и опрос:
// вкладка вернётся уже после того, как джоб уйдёт из показа
// (job.keepFinished — пять секунд). Владелец увидел бы пустой статус, из
// которого следует, что ничего не происходило (ADR-0025, «Честный доклад»).
//
// Область честная и ограниченная. Слот ОДИН: показывается последняя неудача,
// а не история — история требует решения, сколько её хранить и как чистить,
// и ни на один из этих вопросов у нас нет ответа лучше, чем logread.
//
// Перезапуск демона слот НЕ переживает, и это решение, а не недоделка:
// писать его на диск значило бы завести второй источник правды
// (ADR-0002) ради случая, в котором владелец и так идёт читать logread.
type failStore struct {
	mu   sync.Mutex
	fail *Fail
}

// Все три метода терпят нулевой приёмник, и это не небрежность, а
// выравнивание правил. Раньше switchFailed проверял `if s.fails != nil`, а
// соседний verifySwitch звал Clear() без проверки: две функции в одном файле
// жили по разным правилам, и вторая ждала своего nil-указателя. Проверка
// внутри снимает вопрос со всех вызывающих сразу — слот, которого нет,
// нечего заполнять и нечего стирать.
//
// Set запоминает неудачу.
//
// reason — МАШИННЫЙ код из таксономии upstreamhandler.go (тип FailReason), а
// не русская фраза и не голая строка. Именованный тип здесь обязателен:
// ssid и reason — два соседних параметра, и переставленные местами они
// собирались бы молча, а владелец читал бы в панели доклад о сети с именем
// «no_ipv4». Переводит код панель (по kind и arg она уже строит подписи
// джобов сама): словарь на роутере был бы копией словарей панели — вторым
// местом, где строки разъезжаются.
//
// ssid, а не имя секции: владелец выбирал сеть по имени в эфире и опознаёт
// её только так. `wifinet2` в докладе означало бы, что за объяснением
// придётся идти в LuCI.
//
// detail — человекочитаемая подробность в дополнение к коду, и параметр
// добавлен по разбирательству, в котором её не хватило. Код apply_failed
// выставляется шестью путями, панель переводит его одной фразой, и владелец,
// у которого на роутере не оказалось скрипта применения, читал уверенный
// диагноз про механизм, который ни разу не запускался. Текст у вызывающего
// уже собран — терять его на границе слота было нечем оправдать.
//
// Порядок параметров: ssid, reason, detail — то есть от машинного к
// человеческому. Две соседние строки (ssid и detail) переставить местами
// компилятор не мешает, но перепутанные они видны сразу: detail — фраза, а
// не имя сети.
func (s *failStore) Set(ssid string, reason FailReason, detail string, at time.Time) {
	if s == nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.fail = &Fail{
		SSID:   ssid,
		Reason: reason,
		Detail: detail,
		At:     at.UTC().Format(time.RFC3339),
	}
}

// Clear стирает слот. Зовётся УСПЕШНЫМ переключением: неудача, оставшаяся
// висеть рядом с работающей сетью, — это доклад о том, чего уже нет, и
// владелец будет чинить починенное.
func (s *failStore) Clear() {
	if s == nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.fail = nil
}

// Get возвращает КОПИЮ: значение уезжает в тело ответа, которое сериализуется
// уже без замка, а слот к тому времени может быть стёрт успешным
// переключением.
func (s *failStore) Get() *Fail {
	if s == nil {
		return nil
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.fail == nil {
		return nil
	}
	cp := *s.fail
	return &cp
}
