// testNote — итог замера задержек словами.
//
// Демон отвечает 200 даже когда наружу не выбрался ни один узел: движок
// отработал, узлы опрошены, «все мертвы» — такой же результат, как «все
// живы» (контракт, POST /api/nikki/test). Рассказать о нём обязана панель,
// и молчать нельзя: mihomo обновляет задержки сам примерно раз в пять минут,
// поэтому «нажал, а числа те же» неотличимо от неудачи, пока не сказано вслух.
//
// Не ответившие и не замеренные разведены намеренно. Первое — про узел:
// сервер молчит. Второе — про нас: кончился бюджет демона, и о таком узле
// не известно ничего, включая то, жив ли он.
function testNote(sum, t) {
	if (!sum || typeof sum.total !== 'number') return null;
	if (sum.total === 0) return { msg: t('srv.test.empty'), kind: 'warn' };
	if (sum.measured === 0) return { msg: t('srv.test.none', { n: sum.total }), kind: 'err' };
	if (sum.skipped) {
		return { msg: t('srv.test.cut', { ok: sum.measured, n: sum.total }), kind: 'warn' };
	}
	if (sum.failed) {
		return { msg: t('srv.test.part', { ok: sum.measured, n: sum.total, bad: sum.failed }), kind: 'warn' };
	}
	return { msg: t('srv.test.ok', { n: sum.total }), kind: 'info' };
}

function NikkiCard({ data, svc, t, busy, locked, onPick, onTest }) {
	// Заглушка держит и заголовок, и место под нижнюю кнопку: без них
	// карточка подскочила бы на полсотни пикселей ровно в тот момент, когда
	// на неё смотрят.
	//
	// data сам по себе больше не отвечает на вопрос «что показывать»:
	// undefined теперь означает не только «список ещё едет», но и «служба
	// молчит, спрашивать нечего» — так его выставляет эффект в App. Что
	// именно происходит, знает svc, поэтому ветки идут от него.
	//
	// ПОРЯДОК ВЕТОК ЗНАЧИМ, и обе перестановки ломают своё.
	//
	// 'starting' идёт раньше отказа: гонку легко проиграть — 503 от ещё не
	// поднявшегося Clash API прилетает раньше, чем available станет true,
	// и data успевает стать null. Проверь отказ первым — и карточка снова
	// напечатает «не отвечает» про службу, которая нормально запускается.
	//
	// 'down' идёт раньше data === undefined: эффект в App возвращает data
	// в «ещё не спрашивали» именно потому, что служба молчит, так что здесь
	// undefined — норма, а не редкость. Проверь скелетон первым — и он станет
	// вечным, то есть START_GRACE не будет значить ничего.
	const skeleton = (note) => html`<div class="card" aria-busy="true"><h2>${t('srv.title')}</h2>
		<${Skel} n=${3} />
		<div class="skel" style="height:46px;margin-top:12px"></div>${note}</div>`;
	const down = () => html`<div class="card"><h2>${t('srv.title')}</h2><div class="empty">${t('srv.down')}</div></div>`;

	if (svc === 'starting') return skeleton(html`<p class="hint tight">${t('srv.starting')}</p>`);
	if (svc === 'down') return down();
	if (data === undefined) return skeleton(null);
	if (!data || !data.available) return down();
	const members = data.members || [];
	if (!members.length) {
		return html`<div class="card"><h2>${t('srv.title')}</h2><div class="empty">${t('srv.empty')}</div></div>`;
	}
	// pinned приходит от демона отдельным полем: по одному имени узла
	// «движок подобрал» и «закреплено руками» неразличимы, а разница
	// принципиальна — во втором случае автоподбор выключен.
	const pinned = !!data.pinned;
	const active = data.fixed || data.selected;
	// Строка «Авто | Лучший сервер» приезжает вместе со списком — но только
	// когда демон знает манифест подписки. Нет манифеста (свежая установка,
	// ни одного обновления) — нет и строки: демон отдаёт живой список mihomo,
	// в котором все строки узлы.
	//
	// Кнопка в шапке и эта строка делают ОДНО И ТО ЖЕ: POST с именем AUTO.
	// Поэтому вместе они не показываются — два одинаковых контроля в одной
	// карточке заставляют искать между ними разницу, которой нет. Убрать
	// кнопку из шапки насовсем было нельзя ровно из-за случая без манифеста:
	// строки «Авто» там не будет никогда, и закреплённый роутер остался бы
	// без выхода из закрепления иначе как через ssh.
	const hasAuto = members.some((m) => m.kind === 'auto');

	return html`
		<div class="card">
			<h2>${t('srv.title')}
				${!hasAuto && html`
				<button class="linkbtn" disabled=${!pinned || locked} aria-busy=${on(busy, 'proxy', 'AUTO')}
					onClick=${() => onPick('AUTO')}>
					${on(busy, 'proxy', 'AUTO') && html`<${Spin} /> `}${pinned ? t('srv.auto.back') : t('srv.auto')}</button>`}
			</h2>
			${pinned && html`<p class="hint tight" style="color:var(--warn)">${t('srv.pinned.note')}</p>`}
			<div class="rows">
				${members.map((m) => {
					// Строки, которые узлами не являются, разбираются ДО общей
					// ветки, и оформление им выбирает kind, а не alive. У всех
					// трёх alive всегда false, а delay_ms — null, поэтому общий
					// код сказал бы про них две неправды сразу: класс dim
					// («узел мёртв») и пустой метр задержки («узел не ответил»).
					// Мёртвого узла здесь нет — нет узла вовсе.
					if (m.kind === 'separator') {
						// Не кнопка (нажимать нечего: за именем стоит копия
						// соседнего узла) и не aria-hidden. Провайдер режет
						// список заголовками разделов, и тому, кто слушает
						// панель голосом, они говорят ровно то же, что
						// видящему: дальше пойдут узлы для обхода белых
						// списков. Спрятать — значит отдать незрячему список
						// без структуры, которая у зрячего есть.
						return html`<div class="row sep">${m.name}</div>`;
					}
					if (m.kind === 'unsupported') {
						// Причина выводится СТРОКОЙ, а не только в title.
						// На телефоне title не существует: нет ни курсора, ни
						// наведения — а панель открывают именно с телефона и
						// именно тогда, когда интернет не работает. Причина,
						// видимая только с ноутбука, — это причина, которую
						// не показали.
						//
						// Ряд от этого выше, но не дёргается: текст статичен,
						// приезжает вместе со списком и не зависит ни от
						// наведения, ни от занятости. Обрезать его нечем —
						// обрезанное сообщение об ошибке выглядит полным и
						// потому хуже отсутствующего.
						//
						// Текст причины русский (его пишет демон, он же уходит
						// в syslog), поэтому в английском интерфейсе он подан
						// в переведённой рамке: «Not a node: …». Перевести сам
						// текст панель не может, а выдать его за свой — значит
						// соврать про язык интерфейса.
						return html`
						<button class="row unsup" disabled>
							<span class="name">${m.name}</span>
							<span class="ms">${t('srv.unsup.mark')}</span>
							${m.reason && html`<span class="why">${t('srv.unsup.why', { why: m.reason })}</span>`}
						</button>`;
					}
					if (m.kind === 'auto') {
						// Автоподбор работает ровно тогда, когда ничего не
						// закреплено. pinned приходит от демона отдельным
						// полем и по имени узла не вычисляется (см. выше),
						// поэтому активность этой строки показывается тем же
						// способом, что активность узла: класс sel и метка.
						//
						// Строка остаётся нажимаемой и при уже работающем
						// автоподборе — в отличие от кнопки в шапке, которая
						// в этом состоянии гасла. Гасить нельзя: :disabled в
						// этом списке читается как «выключено», и приглушённой
						// оказалась бы единственная строка, которая сейчас
						// верна. Активный узел панель по той же причине тоже
						// не гасит.
						return html`
						<button class="row ${pinned ? '' : 'sel'}"
							disabled=${locked} aria-busy=${on(busy, 'proxy', 'AUTO')}
							onClick=${() => onPick('AUTO')}>
							<span class="name">${m.name}</span>
							${!pinned && html`
								<span class="tag tag-auto" title=${t('srv.tip.auto')}>${t('srv.tag.on')}</span>`}
							<span class="ms">${on(busy, 'proxy', 'AUTO') && html`<${Spin} />`}</span>
						</button>`;
					}
					if (m.kind !== 'node') {
						// Неизвестный вид — закрываемся, как сервер. Демон
						// отбивает выбор всего, что не node, кодом 409, и
						// открытое умолчание здесь дало бы кликабельную
						// строку с отказом на непереведённом тексте. Такое
						// значение может прийти только от манифеста другой
						// версии демона; строка остаётся видимой, но не
						// нажимаемой, без причины — её у нас нет.
						return html`
						<button class="row unsup" disabled>
							<span class="name">${m.name}</span>
							<span class="ms">${t('srv.unsup.mark')}</span>
						</button>`;
					}
					const isActive = active === m.name;
					return html`
					<button class="row ${isActive ? 'sel' : ''} ${m.alive ? '' : 'dim'}"
						disabled=${locked} aria-busy=${on(busy, 'proxy', m.name)}
						onClick=${() => onPick(m.name)}>
						<span class="name">${m.name}</span>
						${isActive && html`
							<span class="tag ${pinned ? 'tag-pin' : 'tag-auto'}"
								title=${pinned ? t('srv.tip.pinned') : t('srv.tip.auto')}>
								${pinned ? '📌 ' + t('srv.tag.pinned') : t('srv.tag.auto')}</span>`}
						<span class="meter"><i class=${latBg(m.delay_ms)} style="width:${latPct(m.delay_ms)}"></i></span>
						<!-- Кольцо занимает слот задержки: у .ms фиксированные 54px,
						     поэтому имя узла не съезжает. Вставка в начало строки
						     сдвинула бы его на 22px вправо — дёрганье ровно на том
						     элементе, за которым в этот момент следят. -->
						<span class="ms ${latClass(m.delay_ms)}">${on(busy, 'proxy', m.name)
							? html`<${Spin} />`
							: (m.delay_ms != null ? m.delay_ms + ' ms' : '—')}</span>
					</button>`;
				})}
			</div>
			<button class="wide" disabled=${locked} aria-busy=${on(busy, 'test')} onClick=${onTest}>
				${on(busy, 'test') ? html`<${Spin} /> ${t('srv.measuring')}` : t('srv.measure')}</button>
		</div>`;
}

