// Потолок жизни джоба. Отсчитывается по МЕСТНЫМ часам от момента, когда панель
// приняла ответ 202, — см. seedAt ниже.
//
// Из eta_sec потолок не выводится, и это принципиально: eta — оценка, а не
// предел. У переключения внешней сети eta_sec равен 20 (openapi), а сам джоб
// вправе идти до 50+: ожидание ассоциации 20 с плюс ожидание адреса IPv4 30 с
// (internal/httpapi/upstreamhandler.go:127-128) плюс применение. «eta плюс
// запас» снимал засев на тридцатой секунде — полоска исчезала, кнопки
// отпирались, панель заявляла, что операции нет, а джоб шёл ещё двадцать
// секунд и следующее нажатие получало 409.
//
// 75 секунд — потолок самой долгой операции плюс запас на пропущенные опросы.
// Для смены режима (5–15 с) число заведомо велико, и это не оплошность:
// задача потолка не оценивать длительность, а не дать засеву пережить джоб
// НАВСЕГДА при упавшем опросе. Оценку показывает полоска, она считает по eta.
const JOB_MAX = 75000;

// Сколько статус вправе не обновляться, прежде чем панель перестаёт верить
// его джобу.
//
// Джоб из статуса — утверждение о том, что происходит ПРЯМО СЕЙЧАС, и живёт
// оно ровно до тех пор, пока подтверждается опросом. Без срока доигранный
// джоб при потере связи оставался «идущим» до F5: полоска, locked, мёртвые
// кнопки. Пятнадцать секунд — это пятнадцать подряд пропущенных опросов,
// заведомо больше перезапуска firewall; плата за срок — окно, в котором
// панель отпустит кнопки над ещё идущим джобом и следующее нажатие получит
// 409 job_busy. Тост про занятость лучше запертой навсегда панели.
//
// Засева этот срок НЕ касается: у него свой отсчёт (JOB_MAX), и он обязан
// переживать устаревший статус — сразу после нажатия устаревший статус штатен,
// ради этого засев и заведён.
const STATUS_TTL = 15000;

// Сколько ждём слушателя службы, прежде чем сказать «не отвечает». Демон
// коммитит UCI mode ДО того, как служба поднялась (internal/httpapi/
// modehandler.go:77-86), поэтому первые секунды нового режима — штатный старт,
// а не отказ. Двадцать секунд: firewall restart плюс запуск b4/nikki на живом
// роутере укладываются в единицы секунд, остальное — запас на холодный старт
// и медленную флешку. Меньше — и панель начнёт врать про исправный роутер,
// больше — и настоящая поломка будет полминуты притворяться загрузкой.
const START_GRACE = 20000;

// Как часто досылать запрос списка, если служба отвечает, а список не доехал.
// Пять секунд, а не каждый тик: это починка редкой гонки, и она не стоит
// секундного долбления роутера, которое на медленном канале само себе мешает.
const RETRY_MS = 5000;

